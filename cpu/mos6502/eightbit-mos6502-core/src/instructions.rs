// Original closed decode of manufacturer-published instruction facts; see README provenance.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum Mode {
    Imm,
    Zp,
    Zpx,
    Zpy,
    Abs,
    Abx,
    Aby,
    Izx,
    Izy,
}
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum Op {
    Adc,
    And,
    Asl,
    Bcc,
    Bcs,
    Beq,
    Bit,
    Bmi,
    Bne,
    Bpl,
    Brk,
    Bvc,
    Bvs,
    Clc,
    Cld,
    Cli,
    Clv,
    Cmp,
    Cpx,
    Cpy,
    Dec,
    Dex,
    Dey,
    Eor,
    Inc,
    Inx,
    Iny,
    Jmi,
    Jmp,
    Jsr,
    Lda,
    Ldx,
    Ldy,
    Lsr,
    Nop,
    Ora,
    Pha,
    Php,
    Pla,
    Plp,
    Rol,
    Ror,
    Rti,
    Rts,
    Sbc,
    Sec,
    Sed,
    Sei,
    Sta,
    Stx,
    Sty,
    Tax,
    Tay,
    Tsx,
    Txa,
    Txs,
    Tya,
}

pub(super) fn decode(opcode: u8) -> Option<(Op, Option<Mode>)> {
    Some(match opcode {
        0x00 => (Op::Brk, None),
        0x01 => (Op::Ora, Some(Mode::Izx)),
        0x05 => (Op::Ora, Some(Mode::Zp)),
        0x06 => (Op::Asl, Some(Mode::Zp)),
        0x08 => (Op::Php, None),
        0x09 => (Op::Ora, Some(Mode::Imm)),
        0x0a => (Op::Asl, None),
        0x0d => (Op::Ora, Some(Mode::Abs)),
        0x0e => (Op::Asl, Some(Mode::Abs)),
        0x10 => (Op::Bpl, None),
        0x11 => (Op::Ora, Some(Mode::Izy)),
        0x15 => (Op::Ora, Some(Mode::Zpx)),
        0x16 => (Op::Asl, Some(Mode::Zpx)),
        0x18 => (Op::Clc, None),
        0x19 => (Op::Ora, Some(Mode::Aby)),
        0x1d => (Op::Ora, Some(Mode::Abx)),
        0x1e => (Op::Asl, Some(Mode::Abx)),
        0x20 => (Op::Jsr, None),
        0x21 => (Op::And, Some(Mode::Izx)),
        0x24 => (Op::Bit, Some(Mode::Zp)),
        0x25 => (Op::And, Some(Mode::Zp)),
        0x26 => (Op::Rol, Some(Mode::Zp)),
        0x28 => (Op::Plp, None),
        0x29 => (Op::And, Some(Mode::Imm)),
        0x2a => (Op::Rol, None),
        0x2c => (Op::Bit, Some(Mode::Abs)),
        0x2d => (Op::And, Some(Mode::Abs)),
        0x2e => (Op::Rol, Some(Mode::Abs)),
        0x30 => (Op::Bmi, None),
        0x31 => (Op::And, Some(Mode::Izy)),
        0x35 => (Op::And, Some(Mode::Zpx)),
        0x36 => (Op::Rol, Some(Mode::Zpx)),
        0x38 => (Op::Sec, None),
        0x39 => (Op::And, Some(Mode::Aby)),
        0x3d => (Op::And, Some(Mode::Abx)),
        0x3e => (Op::Rol, Some(Mode::Abx)),
        0x40 => (Op::Rti, None),
        0x41 => (Op::Eor, Some(Mode::Izx)),
        0x45 => (Op::Eor, Some(Mode::Zp)),
        0x46 => (Op::Lsr, Some(Mode::Zp)),
        0x48 => (Op::Pha, None),
        0x49 => (Op::Eor, Some(Mode::Imm)),
        0x4a => (Op::Lsr, None),
        0x4c => (Op::Jmp, None),
        0x4d => (Op::Eor, Some(Mode::Abs)),
        0x4e => (Op::Lsr, Some(Mode::Abs)),
        0x50 => (Op::Bvc, None),
        0x51 => (Op::Eor, Some(Mode::Izy)),
        0x55 => (Op::Eor, Some(Mode::Zpx)),
        0x56 => (Op::Lsr, Some(Mode::Zpx)),
        0x58 => (Op::Cli, None),
        0x59 => (Op::Eor, Some(Mode::Aby)),
        0x5d => (Op::Eor, Some(Mode::Abx)),
        0x5e => (Op::Lsr, Some(Mode::Abx)),
        0x60 => (Op::Rts, None),
        0x61 => (Op::Adc, Some(Mode::Izx)),
        0x65 => (Op::Adc, Some(Mode::Zp)),
        0x66 => (Op::Ror, Some(Mode::Zp)),
        0x68 => (Op::Pla, None),
        0x69 => (Op::Adc, Some(Mode::Imm)),
        0x6a => (Op::Ror, None),
        0x6c => (Op::Jmi, None),
        0x6d => (Op::Adc, Some(Mode::Abs)),
        0x6e => (Op::Ror, Some(Mode::Abs)),
        0x70 => (Op::Bvs, None),
        0x71 => (Op::Adc, Some(Mode::Izy)),
        0x75 => (Op::Adc, Some(Mode::Zpx)),
        0x76 => (Op::Ror, Some(Mode::Zpx)),
        0x78 => (Op::Sei, None),
        0x79 => (Op::Adc, Some(Mode::Aby)),
        0x7d => (Op::Adc, Some(Mode::Abx)),
        0x7e => (Op::Ror, Some(Mode::Abx)),
        0x81 => (Op::Sta, Some(Mode::Izx)),
        0x84 => (Op::Sty, Some(Mode::Zp)),
        0x85 => (Op::Sta, Some(Mode::Zp)),
        0x86 => (Op::Stx, Some(Mode::Zp)),
        0x88 => (Op::Dey, None),
        0x8a => (Op::Txa, None),
        0x8c => (Op::Sty, Some(Mode::Abs)),
        0x8d => (Op::Sta, Some(Mode::Abs)),
        0x8e => (Op::Stx, Some(Mode::Abs)),
        0x90 => (Op::Bcc, None),
        0x91 => (Op::Sta, Some(Mode::Izy)),
        0x94 => (Op::Sty, Some(Mode::Zpx)),
        0x95 => (Op::Sta, Some(Mode::Zpx)),
        0x96 => (Op::Stx, Some(Mode::Zpy)),
        0x98 => (Op::Tya, None),
        0x99 => (Op::Sta, Some(Mode::Aby)),
        0x9a => (Op::Txs, None),
        0x9d => (Op::Sta, Some(Mode::Abx)),
        0xa0 => (Op::Ldy, Some(Mode::Imm)),
        0xa1 => (Op::Lda, Some(Mode::Izx)),
        0xa2 => (Op::Ldx, Some(Mode::Imm)),
        0xa4 => (Op::Ldy, Some(Mode::Zp)),
        0xa5 => (Op::Lda, Some(Mode::Zp)),
        0xa6 => (Op::Ldx, Some(Mode::Zp)),
        0xa8 => (Op::Tay, None),
        0xa9 => (Op::Lda, Some(Mode::Imm)),
        0xaa => (Op::Tax, None),
        0xac => (Op::Ldy, Some(Mode::Abs)),
        0xad => (Op::Lda, Some(Mode::Abs)),
        0xae => (Op::Ldx, Some(Mode::Abs)),
        0xb0 => (Op::Bcs, None),
        0xb1 => (Op::Lda, Some(Mode::Izy)),
        0xb4 => (Op::Ldy, Some(Mode::Zpx)),
        0xb5 => (Op::Lda, Some(Mode::Zpx)),
        0xb6 => (Op::Ldx, Some(Mode::Zpy)),
        0xb8 => (Op::Clv, None),
        0xb9 => (Op::Lda, Some(Mode::Aby)),
        0xba => (Op::Tsx, None),
        0xbc => (Op::Ldy, Some(Mode::Abx)),
        0xbd => (Op::Lda, Some(Mode::Abx)),
        0xbe => (Op::Ldx, Some(Mode::Aby)),
        0xc0 => (Op::Cpy, Some(Mode::Imm)),
        0xc1 => (Op::Cmp, Some(Mode::Izx)),
        0xc4 => (Op::Cpy, Some(Mode::Zp)),
        0xc5 => (Op::Cmp, Some(Mode::Zp)),
        0xc6 => (Op::Dec, Some(Mode::Zp)),
        0xc8 => (Op::Iny, None),
        0xc9 => (Op::Cmp, Some(Mode::Imm)),
        0xca => (Op::Dex, None),
        0xcc => (Op::Cpy, Some(Mode::Abs)),
        0xcd => (Op::Cmp, Some(Mode::Abs)),
        0xce => (Op::Dec, Some(Mode::Abs)),
        0xd0 => (Op::Bne, None),
        0xd1 => (Op::Cmp, Some(Mode::Izy)),
        0xd5 => (Op::Cmp, Some(Mode::Zpx)),
        0xd6 => (Op::Dec, Some(Mode::Zpx)),
        0xd8 => (Op::Cld, None),
        0xd9 => (Op::Cmp, Some(Mode::Aby)),
        0xdd => (Op::Cmp, Some(Mode::Abx)),
        0xde => (Op::Dec, Some(Mode::Abx)),
        0xe0 => (Op::Cpx, Some(Mode::Imm)),
        0xe1 => (Op::Sbc, Some(Mode::Izx)),
        0xe4 => (Op::Cpx, Some(Mode::Zp)),
        0xe5 => (Op::Sbc, Some(Mode::Zp)),
        0xe6 => (Op::Inc, Some(Mode::Zp)),
        0xe8 => (Op::Inx, None),
        0xe9 => (Op::Sbc, Some(Mode::Imm)),
        0xea => (Op::Nop, None),
        0xec => (Op::Cpx, Some(Mode::Abs)),
        0xed => (Op::Sbc, Some(Mode::Abs)),
        0xee => (Op::Inc, Some(Mode::Abs)),
        0xf0 => (Op::Beq, None),
        0xf1 => (Op::Sbc, Some(Mode::Izy)),
        0xf5 => (Op::Sbc, Some(Mode::Zpx)),
        0xf6 => (Op::Inc, Some(Mode::Zpx)),
        0xf8 => (Op::Sed, None),
        0xf9 => (Op::Sbc, Some(Mode::Aby)),
        0xfd => (Op::Sbc, Some(Mode::Abx)),
        0xfe => (Op::Inc, Some(Mode::Abx)),
        _ => return None,
    })
}
