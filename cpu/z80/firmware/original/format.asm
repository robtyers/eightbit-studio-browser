LD A,'.'
CALL FMT_EMIT
JR FMT_FRACTION
FMT_NEGATIVE_EXPONENT:
CP $fb
JR C,FMT_SCIENTIFIC
JR NZ,FMT_SMALL_FIXED
LD A,(IX-5)
CP 1
