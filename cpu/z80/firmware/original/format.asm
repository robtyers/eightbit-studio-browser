FMT_BUFFER:
LD (IX-5),B
LD BC,20
LD HL,(STKBOT)
CALL CREATE_TEMP
LD (IX-8),L
LD (IX-7),H
LD (IX-10),L
LD (IX-9),H
LD A,(IX-2)
OR A
LD A,'-'
CALL NZ,FMT_EMIT
PUSH IX
POP HL
LD DE,$ffec
ADD HL,DE
LD A,(IX-1)
BIT 7,A
JR NZ,FMT_NEGATIVE_EXPONENT
CP 13
JR NC,FMT_SCIENTIFIC
INC A
LD (IX-6),A
FMT_INTEGER_DIGIT:
LD A,(IX-5)
OR A
JR Z,FMT_INTEGER_ZERO
LD A,(HL)
INC HL
DEC (IX-5)
JR FMT_INTEGER_WRITE
FMT_INTEGER_ZERO:
LD A,'0'
FMT_INTEGER_WRITE:
CALL FMT_EMIT
DEC (IX-6)
JR NZ,FMT_INTEGER_DIGIT
LD A,(IX-5)
OR A
