; Original five-byte floating-point arithmetic. All work executes on the Z80.
; Internal operands: guard, four little-endian mantissa bytes, exponent word, sign.
MAIN_PROMPT EQU $2000
FP_ENTRY:
CP 24
JP NC,MATH_ACCESS
CP 10
JP Z,FP_RANDOM
CP 4
JP NC,FP_EXTENDED
PUSH AF
CALL FP_UNPACK_TWO
POP AF
CP 2
JP Z,FP_MULTIPLY
CP 3
JP Z,FP_DIVIDE
OR A
JR Z,FP_ADD
LD A,(FP_B+7)
XOR $80
LD (FP_B+7),A
FP_ADD:
LD A,(FP_A+5)
OR A
JR NZ,FP_A_NONZERO
CALL FP_SWAP
JP FP_FINISH
FP_A_NONZERO:
LD A,(FP_B+5)
OR A
JP Z,FP_FINISH
LD B,A
LD A,(FP_A+5)
CP B
CALL C,FP_SWAP
FP_ALIGN:
LD A,(FP_A+5)
LD HL,FP_B+5
CP (HL)
JR Z,FP_ALIGNED
LD IY,FP_B
CALL FP_SHIFT_RIGHT
LD HL,FP_B+5
INC (HL)
JR FP_ALIGN
FP_ALIGNED:
LD A,(FP_A+7)
LD HL,FP_B+7
XOR (HL)
JP NZ,FP_SUBTRACT
LD HL,FP_B
LD DE,FP_A
LD B,5
OR A
FP_ADD_BYTE:
LD A,(DE)
ADC A,(HL)
LD (DE),A
INC DE
INC HL
DJNZ FP_ADD_BYTE
JR NC,FP_FINISH
LD IY,FP_A
CALL FP_SHIFT_RIGHT_CARRY
LD HL,(FP_A+5)
INC HL
LD (FP_A+5),HL
JR FP_FINISH
FP_SUBTRACT:
LD HL,FP_A+4
LD DE,FP_B+4
LD B,5
FP_COMPARE_BYTE:
LD A,(DE)
LD C,A
LD A,(HL)
CP C
JR C,FP_SUBTRACT_SWAP
JR NZ,FP_SUBTRACT_ORDERED
DEC HL
DEC DE
DJNZ FP_COMPARE_BYTE
JR FP_SUBTRACT_ORDERED
FP_SUBTRACT_SWAP:
CALL FP_SWAP
FP_SUBTRACT_ORDERED:
LD HL,FP_B
LD DE,FP_A
LD B,5
OR A
FP_SUBTRACT_BYTE:
LD A,(DE)
SBC A,(HL)
LD (DE),A
INC DE
INC HL
DJNZ FP_SUBTRACT_BYTE
FP_FINISH:
LD IY,FP_A
CALL FP_NORMALISE
CALL FP_ROUND
JP FP_PACK

FP_SWAP:
LD HL,FP_A
LD DE,FP_B
LD B,8
FP_SWAP_BYTE:
LD A,(DE)
LD C,A
LD A,(HL)
LD (DE),A
LD (HL),C
INC DE
INC HL
DJNZ FP_SWAP_BYTE
RET

FP_SHIFT_RIGHT:
OR A
FP_SHIFT_RIGHT_CARRY:
RR (IY+4)
RR (IY+3)
RR (IY+2)
RR (IY+1)
RR (IY+0)
RET NC
SET 0,(IY+0)
RET

FP_NORMALISE:
LD A,(IY+0)
OR (IY+1)
OR (IY+2)
OR (IY+3)
OR (IY+4)
JR Z,FP_ZERO
FP_NORMALISE_LOOP:
BIT 7,(IY+4)
JR NZ,FP_CHECK_RANGE
SLA (IY+0)
RL (IY+1)
RL (IY+2)
RL (IY+3)
RL (IY+4)
LD L,(IY+5)
LD H,(IY+6)
DEC HL
LD (IY+5),L
LD (IY+6),H
JR FP_NORMALISE_LOOP
FP_CHECK_RANGE:
LD A,(IY+6)
OR A
JP P,FP_CHECK_LOW
JR FP_ZERO
FP_CHECK_LOW:
JP NZ,FP_OVERFLOW
LD A,(IY+5)
OR A
RET NZ
FP_ZERO:
LD B,8
PUSH IY
POP HL
XOR A
FP_ZERO_BYTE:
LD (HL),A
INC HL
DJNZ FP_ZERO_BYTE
RET

FP_ROUND:
BIT 7,(IY+0)
RET Z
LD (IY+0),0
INC (IY+1)
RET NZ
INC (IY+2)
RET NZ
INC (IY+3)
RET NZ
INC (IY+4)
RET NZ
LD (IY+4),$80
LD L,(IY+5)
LD H,(IY+6)
INC HL
LD (IY+5),L
LD (IY+6),H
JP FP_CHECK_RANGE

FP_UNPACK_TWO:
LD BC,10
CALL STACK_REQUIRE
LD (STKEND),HL
LD IY,FP_A
CALL FP_UNPACK
LD IY,FP_B
JP FP_UNPACK

FP_UNPACK:
PUSH HL
LD (IY+0),0
LD A,(HL)
LD (IY+5),A
LD (IY+6),0
INC HL
OR A
JR Z,FP_UNPACK_INTEGER
LD A,(HL)
AND $80
LD (IY+7),A
LD A,(HL)
AND $7f
OR $80
LD (IY+4),A
INC HL
LD A,(HL)
LD (IY+3),A
INC HL
LD A,(HL)
LD (IY+2),A
INC HL
LD A,(HL)
LD (IY+1),A
JR FP_UNPACK_RETURN
FP_UNPACK_INTEGER:
LD A,(HL)
AND $80
LD (IY+7),A
INC HL
LD C,(HL)
INC HL
LD B,(HL)
LD A,(IY+7)
OR A
JR Z,FP_UNPACK_POSITIVE
LD HL,0
OR A
SBC HL,BC
LD B,H
LD C,L
LD A,B
OR C
LD A,0
JR NZ,FP_UNPACK_MAGNITUDE
INC A
JR FP_UNPACK_MAGNITUDE
FP_UNPACK_POSITIVE:
XOR A
FP_UNPACK_MAGNITUDE:
LD (IY+1),C
LD (IY+2),B
LD (IY+3),A
LD (IY+4),0
LD (IY+5),160
CALL FP_NORMALISE
FP_UNPACK_RETURN:
POP HL
LD BC,5
ADD HL,BC
RET

FP_PACK:
LD HL,(STKEND)
LD A,(FP_A+5)
LD (HL),A
INC HL
OR A
JR NZ,FP_PACK_NONZERO
LD B,4
FP_PACK_ZERO:
LD (HL),0
INC HL
DJNZ FP_PACK_ZERO
JR FP_PACK_RETURN
FP_PACK_NONZERO:
LD A,(FP_A+4)
AND $7f
LD B,A
LD A,(FP_A+7)
OR B
LD (HL),A
INC HL
LD A,(FP_A+3)
LD (HL),A
INC HL
LD A,(FP_A+2)
LD (HL),A
INC HL
LD A,(FP_A+1)
LD (HL),A
INC HL
FP_PACK_RETURN:
LD (STKEND),HL
RET

; Binary multiplication, retaining 40 significant/guard bits and a sticky bit.
FP_MULTIPLY:
LD HL,(FP_A+5)
LD DE,(FP_B+5)
ADD HL,DE
LD DE,128
OR A
SBC HL,DE
PUSH HL
LD A,(FP_A+7)
LD HL,FP_B+7
XOR (HL)
PUSH AF
LD HL,FP_A+1
LD DE,FP_A
LD BC,4
LDIR
LD HL,FP_A+4
LD B,4
XOR A
FP_MULTIPLY_CLEAR_HIGH:
LD (HL),A
INC HL
DJNZ FP_MULTIPLY_CLEAR_HIGH
LD HL,FP_A+16
LD B,8
FP_MULTIPLY_CLEAR_PRODUCT:
LD (HL),A
INC HL
DJNZ FP_MULTIPLY_CLEAR_PRODUCT
LD A,32
LD (FP_B+7),A
FP_MULTIPLY_LOOP:
LD IY,FP_B
SRL (IY+4)
RR (IY+3)
RR (IY+2)
RR (IY+1)
JR NC,FP_MULTIPLY_SKIP_ADD
LD HL,FP_A
LD DE,FP_A+16
LD B,8
OR A
FP_MULTIPLY_ADD:
LD A,(DE)
ADC A,(HL)
LD (DE),A
INC DE
INC HL
DJNZ FP_MULTIPLY_ADD
FP_MULTIPLY_SKIP_ADD:
LD IY,FP_A
SLA (IY+0)
RL (IY+1)
RL (IY+2)
RL (IY+3)
RL (IY+4)
RL (IY+5)
RL (IY+6)
RL (IY+7)
LD HL,FP_B+7
DEC (HL)
JR NZ,FP_MULTIPLY_LOOP
POP AF
LD (FP_A+7),A
POP HL
LD (FP_A+5),HL
LD A,(FP_A+16)
LD B,A
LD A,(FP_A+17)
OR B
LD B,A
LD A,(FP_A+18)
OR B
JR Z,FP_MULTIPLY_EXACT_LOW
LD HL,FP_A+19
SET 0,(HL)
FP_MULTIPLY_EXACT_LOW:
LD HL,FP_A+19
LD DE,FP_A
LD BC,5
LDIR
JP FP_FINISH

; Restoring binary division: one integer bit followed by 39 fractional bits.
FP_DIVIDE:
LD A,(FP_B+5)
OR A
JP Z,FP_OVERFLOW
LD HL,(FP_A+5)
LD DE,(FP_B+5)
OR A
SBC HL,DE
LD DE,129
ADD HL,DE
PUSH HL
LD A,(FP_A+7)
LD HL,FP_B+7
XOR (HL)
PUSH AF
LD HL,FP_A+1
LD DE,FP_A+16
LD BC,4
LDIR
XOR A
LD (FP_A+20),A
LD HL,FP_A
LD B,5
FP_DIVIDE_CLEAR_QUOTIENT:
LD (HL),A
INC HL
DJNZ FP_DIVIDE_CLEAR_QUOTIENT
LD A,40
LD (FP_B+7),A
FP_DIVIDE_LOOP:
CALL FP_DIVIDE_BIT
LD IY,FP_A
RL (IY+0)
RL (IY+1)
RL (IY+2)
RL (IY+3)
RL (IY+4)
LD IY,FP_A+16
SLA (IY+0)
RL (IY+1)
RL (IY+2)
RL (IY+3)
RL (IY+4)
LD HL,FP_B+7
DEC (HL)
JR NZ,FP_DIVIDE_LOOP
LD A,(FP_A+16)
LD B,A
LD A,(FP_A+17)
OR B
LD B,A
LD A,(FP_A+18)
OR B
LD B,A
LD A,(FP_A+19)
OR B
LD B,A
LD A,(FP_A+20)
OR B
JR Z,FP_DIVIDE_EXACT
LD HL,FP_A
SET 0,(HL)
FP_DIVIDE_EXACT:
POP AF
LD (FP_A+7),A
POP HL
LD (FP_A+5),HL
JP FP_FINISH

FP_DIVIDE_BIT:
LD A,(FP_A+20)
OR A
JR NZ,FP_DIVIDE_SUBTRACT
LD HL,FP_A+19
LD DE,FP_B+4
LD B,4
FP_DIVIDE_COMPARE:
LD A,(DE)
LD C,A
LD A,(HL)
CP C
JR C,FP_DIVIDE_ZERO_BIT
JR NZ,FP_DIVIDE_SUBTRACT
DEC HL
DEC DE
DJNZ FP_DIVIDE_COMPARE
FP_DIVIDE_SUBTRACT:
LD HL,FP_B+1
LD DE,FP_A+16
LD B,4
OR A
FP_DIVIDE_SUBTRACT_BYTE:
LD A,(DE)
SBC A,(HL)
LD (DE),A
INC DE
INC HL
DJNZ FP_DIVIDE_SUBTRACT_BYTE
LD A,(FP_A+20)
SBC A,0
LD (FP_A+20),A
SCF
RET
FP_DIVIDE_ZERO_BIT:
OR A
RET

FP_OVERFLOW:
LD A,5
LD (ERR_NR),A
JP REPORT_ERROR

FP_EXTENDED:
CP 16
JP NC,FP_COMPARE_ENTRY
CP 10
JP NC,REPORT_ERROR
PUSH AF
CALL FP_UNPACK_ONE
POP AF
CP 4
JP Z,FP_NEGATE
CP 5
JP Z,FP_ABSOLUTE
CP 6
JP Z,FP_SIGN
CP 7
JP Z,FP_INTEGER
CP 8
JP Z,FP_WORD
LD A,(FP_A+5)
OR A
JP Z,FP_TRUE
JP FP_FALSE

FP_UNPACK_ONE:
LD BC,5
CALL STACK_REQUIRE
LD (STKEND),HL
LD IY,FP_A
JP FP_UNPACK

FP_NEGATE:
LD A,(FP_A+7)
XOR $80
LD (FP_A+7),A
JP FP_FINISH
FP_ABSOLUTE:
LD A,0
LD (FP_A+7),A
JP FP_FINISH
FP_SIGN:
LD A,(FP_A+5)
OR A
JP Z,FP_FALSE
LD A,(FP_A+7)
PUSH AF
LD IY,FP_A
CALL FP_ZERO
POP AF
LD (FP_A+7),A
LD (IY+4),$80
LD (IY+5),129
JP FP_PACK

FP_INTEGER:
LD A,(FP_A+5)
CP 129
JR C,FP_INTEGER_SMALL
CP 160
JP NC,FP_FINISH
LD C,A
LD A,160
SUB C
LD B,A
LD IY,FP_A
FP_INTEGER_SHIFT:
CALL FP_SHIFT_RIGHT
DJNZ FP_INTEGER_SHIFT
LD A,(FP_A+7)
OR A
JR Z,FP_INTEGER_READY
LD A,(FP_A)
OR A
JR Z,FP_INTEGER_READY
CALL FP_INCREMENT_MAGNITUDE
FP_INTEGER_READY:
LD (IY+0),0
LD (IY+5),160
LD (IY+6),0
JP FP_FINISH
FP_INTEGER_SMALL:
LD A,(FP_A+5)
OR A
JP Z,FP_FALSE
LD A,(FP_A+7)
OR A
JP Z,FP_FALSE
LD IY,FP_A
CALL FP_ZERO
LD (IY+7),$80
LD (IY+4),$80
LD (IY+5),129
JP FP_PACK

FP_INCREMENT_MAGNITUDE:
INC (IY+1)
RET NZ
INC (IY+2)
RET NZ
INC (IY+3)
RET NZ
INC (IY+4)
RET

FP_WORD:
LD A,(FP_A+5)
CP 128
JP C,FP_FALSE
CP 145
JP NC,FP_INTEGER_RANGE
LD C,A
LD A,160
SUB C
LD B,A
LD IY,FP_A
FP_WORD_SHIFT:
CALL FP_SHIFT_RIGHT
DJNZ FP_WORD_SHIFT
BIT 7,(IY+0)
CALL NZ,FP_INCREMENT_MAGNITUDE
LD A,(IY+3)
OR (IY+4)
JP NZ,FP_INTEGER_RANGE
LD A,(IY+7)
OR A
JP NZ,FP_INTEGER_RANGE
LD HL,(STKEND)
LD (HL),0
INC HL
LD (HL),0
INC HL
LD A,(IY+1)
LD (HL),A
INC HL
LD A,(IY+2)
LD (HL),A
INC HL
LD (HL),0
INC HL
LD (STKEND),HL
RET
FP_INTEGER_RANGE:
LD A,10
LD (ERR_NR),A
JP REPORT_ERROR

FP_COMPARE_ENTRY:
CP 24
JP NC,REPORT_ERROR
PUSH AF
CALL FP_UNPACK_TWO
POP AF
CP 22
JR Z,FP_AND
CP 23
JR Z,FP_OR
PUSH AF
CALL FP_COMPARE
LD E,A
POP BC
LD A,B
SUB 16
JR Z,FP_EQUAL
DEC A
JR Z,FP_LESS_THAN
DEC A
JR Z,FP_GREATER_THAN
DEC A
JR Z,FP_LESS_EQUAL
DEC A
JR Z,FP_GREATER_EQUAL
LD A,E
OR A
JP NZ,FP_TRUE
JP FP_FALSE
FP_EQUAL:
LD A,E
OR A
JP Z,FP_TRUE
JP FP_FALSE
FP_LESS_THAN:
BIT 7,E
JP NZ,FP_TRUE
JP FP_FALSE
FP_GREATER_THAN:
LD A,E
CP 1
JP Z,FP_TRUE
JP FP_FALSE
FP_LESS_EQUAL:
LD A,E
CP 1
JP NZ,FP_TRUE
JP FP_FALSE
FP_GREATER_EQUAL:
BIT 7,E
JP Z,FP_TRUE
JP FP_FALSE
FP_AND:
LD A,(FP_B+5)
OR A
JP Z,FP_FALSE
JP FP_FINISH
FP_OR:
LD A,(FP_B+5)
OR A
JP NZ,FP_TRUE
JP FP_FINISH

FP_COMPARE:
LD A,(FP_A+7)
LD HL,FP_B+7
XOR (HL)
JR Z,FP_COMPARE_MAGNITUDE
LD A,(FP_A+7)
OR A
LD A,1
RET Z
LD A,255
RET
FP_COMPARE_MAGNITUDE:
LD A,(FP_B+5)
LD B,A
LD A,(FP_A+5)
CP B
JR C,FP_COMPARE_LESS
JR NZ,FP_COMPARE_GREATER
LD HL,FP_A+4
LD DE,FP_B+4
LD B,4
FP_COMPARE_MANTISSA:
LD A,(DE)
LD C,A
LD A,(HL)
CP C
JR C,FP_COMPARE_LESS
JR NZ,FP_COMPARE_GREATER
DEC HL
DEC DE
DJNZ FP_COMPARE_MANTISSA
XOR A
RET
FP_COMPARE_LESS:
LD A,(FP_A+7)
OR A
LD A,255
RET Z
LD A,1
RET
FP_COMPARE_GREATER:
LD A,(FP_A+7)
OR A
LD A,1
RET Z
LD A,255
RET

FP_FALSE:
LD IY,FP_A
CALL FP_ZERO
JP FP_PACK
FP_TRUE:
LD IY,FP_A
CALL FP_ZERO
LD (IY+4),$80
LD (IY+5),129
JP FP_PACK

; The published recurrence is modulo the prime 65537, without host assistance.
FP_RANDOM:
CALL CHECK_STACK
LD BC,(SEED)
INC BC
LD A,B
OR C
LD A,0
JR NZ,FP_RANDOM_HIGH
INC A
FP_RANDOM_HIGH:
LD (FP_A),A
LD HL,0
LD DE,0
LD A,75
FP_RANDOM_PRODUCT:
PUSH AF
ADD HL,BC
JR NC,FP_RANDOM_NO_CARRY
INC DE
FP_RANDOM_NO_CARRY:
LD A,(FP_A)
ADD A,E
LD E,A
JR NC,FP_RANDOM_NO_HIGH_CARRY
INC D
FP_RANDOM_NO_HIGH_CARRY:
POP AF
DEC A
JR NZ,FP_RANDOM_PRODUCT
OR A
SBC HL,DE
JR C,FP_RANDOM_SEED
DEC HL
FP_RANDOM_SEED:
LD (SEED),HL
PUSH HL
LD IY,FP_A
CALL FP_ZERO
POP HL
LD (IY+1),L
LD (IY+2),H
LD (IY+5),144
JP FP_FINISH
