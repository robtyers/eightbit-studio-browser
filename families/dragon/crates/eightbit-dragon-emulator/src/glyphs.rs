#[cfg(test)]
mod tests {
    use super::glyph;
    #[test]
    fn the_complete_vdg_character_set_has_bounded_original_drawings() {
        assert_eq!(glyph(b' '), [0; 7]);
        for character in 33..=95 {
            let rows = glyph(character);
            assert!(rows.iter().all(|row| *row < 32));
            assert!(rows.iter().any(|row| *row != 0), "character {character}");
        }
    }
}
