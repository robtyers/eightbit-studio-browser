; Native numeric variable records in the published VARS..E_LINE layout.
MAIN_PROMPT EQU $2000
DEST EQU $5c4d
VARIABLE_ENTRY:
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$fff0
ADD HL,SP
LD SP,HL
LD (IX-9),A
CALL CHECK_STACK
CP 1
JR Z,VARIABLE_ASSIGN_NAME
LD HL,(CH_ADD)
JR VARIABLE_NAME_START
VARIABLE_ASSIGN_NAME:
LD HL,(DEST)
VARIABLE_NAME_START:
LD A,(HL)
CP 32
JR NZ,VARIABLE_NAME_FIRST
INC HL
JR VARIABLE_NAME_START
VARIABLE_NAME_FIRST:
OR $20
CP 'a'
JP C,VARIABLE_SYNTAX
CP 'z'+1
JP NC,VARIABLE_SYNTAX
LD (IX-10),A
LD (IX-2),L
LD (IX-1),H
LD BC,0
VARIABLE_NAME_SCAN:
LD A,(HL)
CP 32
JR Z,VARIABLE_NAME_SPACE
OR $20
CP 'a'
JR C,VARIABLE_NAME_DIGIT
CP 'z'+1
JR C,VARIABLE_NAME_ACCEPT
JR VARIABLE_NAME_END
VARIABLE_NAME_DIGIT:
CP '0'
JR C,VARIABLE_NAME_END
CP '9'+1
JR NC,VARIABLE_NAME_END
VARIABLE_NAME_ACCEPT:
INC BC
LD A,B
CP 16
JP NC,VARIABLE_SYNTAX
VARIABLE_NAME_SPACE:
INC HL
JR VARIABLE_NAME_SCAN
VARIABLE_NAME_END:
LD (IX-4),C
LD (IX-3),B
LD A,(IX-9)
CP 1
JR Z,VARIABLE_LOOKUP
LD (CH_ADD),HL
LD L,(IX-2)
LD H,(IX-1)
LD (DEST),HL
CP 2
JP Z,VARIABLE_RETURN
VARIABLE_LOOKUP:
LD HL,($5c4b)
VARIABLE_LOOKUP_RECORD:
LD A,(HL)
CP $80
JP Z,VARIABLE_MISSING
PUSH HL
CALL VARIABLE_MATCH
JR NC,VARIABLE_NO_MATCH
POP DE
JP VARIABLE_FOUND
VARIABLE_NO_MATCH:
POP HL
CALL VARIABLE_SKIP
JR VARIABLE_LOOKUP_RECORD

VARIABLE_MATCH:
LD A,(IX-10)
AND 31
LD B,A
LD A,(HL)
AND 31
CP B
JR NZ,VARIABLE_NOT_MATCHED
LD C,(IX-4)
LD B,(IX-3)
DEC BC
LD A,B
OR C
JR NZ,VARIABLE_MATCH_LONG
LD A,(HL)
AND $e0
CP $60
JR Z,VARIABLE_MATCHED_SHORT
CP $e0
JR NZ,VARIABLE_NOT_MATCHED
VARIABLE_MATCHED_SHORT:
INC HL
SCF
RET
VARIABLE_MATCH_LONG:
LD A,(HL)
AND $e0
CP $a0
JR NZ,VARIABLE_NOT_MATCHED
INC HL
LD E,(IX-2)
LD D,(IX-1)
INC DE
VARIABLE_MATCH_BYTE:
LD A,(DE)
CP 32
JR NZ,VARIABLE_MATCH_CHARACTER
INC DE
JR VARIABLE_MATCH_BYTE
VARIABLE_MATCH_CHARACTER:
OR $20
LD (IX-14),A
LD A,(HL)
LD (IX-13),A
AND $7f
CP (IX-14)
JR NZ,VARIABLE_NOT_MATCHED
INC HL
INC DE
DEC BC
LD A,B
OR C
JR Z,VARIABLE_MATCH_END
BIT 7,(IX-13)
JR Z,VARIABLE_MATCH_BYTE
VARIABLE_NOT_MATCHED:
OR A
RET
VARIABLE_MATCH_END:
BIT 7,(IX-13)
JR Z,VARIABLE_NOT_MATCHED
SCF
RET

VARIABLE_SKIP:
LD A,(HL)
INC HL
AND $e0
CP $60
JR Z,VARIABLE_SKIP_FIVE
CP $e0
JR Z,VARIABLE_SKIP_FOR
CP $a0
JR Z,VARIABLE_SKIP_NAME
; Strings and arrays carry the extent directly after their header.
LD C,(HL)
INC HL
LD B,(HL)
INC HL
ADD HL,BC
RET
VARIABLE_SKIP_FOR:
LD BC,18
ADD HL,BC
RET
VARIABLE_SKIP_NAME:
LD A,(HL)
INC HL
BIT 7,A
JR Z,VARIABLE_SKIP_NAME
VARIABLE_SKIP_FIVE:
LD BC,5
ADD HL,BC
RET

VARIABLE_MISSING:
LD A,(IX-9)
CP 1
JP NZ,VARIABLE_NOT_FOUND
; Keep the two starts fixed while insertion relocates every following pointer.
LD DE,($5c4b)
LD (IX-6),E
LD (IX-5),D
LD DE,(PROG)
LD (IX-8),E
LD (IX-7),D
LD C,(IX-4)
LD B,(IX-3)
INC BC
INC BC
INC BC
INC BC
INC BC
CALL MAKE_ROOM
LD E,(IX-6)
LD D,(IX-5)
LD ($5c4b),DE
LD E,(IX-8)
LD D,(IX-7)
LD (PROG),DE
LD A,(IX-10)
AND 31
OR $60
LD (HL),A
INC HL
LD C,(IX-4)
LD B,(IX-3)
DEC BC
LD A,B
OR C
JR Z,VARIABLE_FOUND
DEC HL
LD A,(HL)
XOR $c0
LD (HL),A
INC HL
LD DE,(DEST)
INC DE
VARIABLE_COPY_NAME:
LD A,(DE)
INC DE
CP 32
JR Z,VARIABLE_COPY_NAME
OR $20
LD (HL),A
INC HL
DEC BC
LD A,B
OR C
JR NZ,VARIABLE_COPY_NAME
DEC HL
SET 7,(HL)
INC HL

VARIABLE_FOUND:
LD (DEST),HL
LD A,(IX-9)
CP 1
JR Z,VARIABLE_STORE
CALL CHECK_STACK
LD DE,(STKEND)
LD BC,5
LDIR
LD (STKEND),DE
LD HL,FLAGS
SET 6,(HL)
JR VARIABLE_RETURN
VARIABLE_STORE:
LD HL,(STKEND)
LD BC,5
OR A
SBC HL,BC
LD (STKEND),HL
LD DE,(STKBOT)
PUSH HL
OR A
SBC HL,DE
JP C,OUT_OF_MEMORY
POP HL
LD DE,(DEST)
LD BC,5
LDIR
VARIABLE_RETURN:
LD SP,IX
POP IX
RET
VARIABLE_NOT_FOUND:
LD A,1
LD (ERR_NR),A
JP REPORT_ERROR
VARIABLE_SYNTAX:
LD A,11
LD (ERR_NR),A
JP REPORT_ERROR
