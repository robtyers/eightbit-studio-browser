; Original listing and report formatting; text is the public report vocabulary.
MAIN_PROMPT EQU $2000
SYSTEM_ENTRY:
OR A
JP Z,SYSTEM_REPORT
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$fff0
ADD HL,SP
LD SP,HL
LD (IX-2),C
LD (IX-1),B
LD (IX-7),A
CP 2
JP Z,SYSTEM_AUTO_LIST
LD HL,(PROG)
LIST_LINE:
LD A,(IX-7)
CP 2
JR NZ,LIST_BOUNDS
LD A,(IX-8)
OR A
JR Z,LIST_BOUNDS
LD A,($5c6b)
INC A
LD B,A
LD A,(S_POSN+1)
CP B
JP Z,LIST_RETURN
JP C,LIST_RETURN
LIST_BOUNDS:
LD DE,($5c4b)
PUSH HL
OR A
SBC HL,DE
POP HL
JP NC,LIST_RETURN
LD B,(HL)
INC HL
LD C,(HL)
INC HL
LD E,(HL)
INC HL
LD D,(HL)
INC HL
LD (IX-4),L
LD (IX-3),H
ADD HL,DE
LD (IX-6),L
LD (IX-5),H
LD H,B
LD L,C
LD E,(IX-2)
LD D,(IX-1)
OR A
SBC HL,DE
JR C,LIST_NEXT_LINE
LD A,(IX-7)
CP 2
JR NZ,LIST_NUMBER
LD H,B
LD L,C
LD DE,($5c49)
OR A
SBC HL,DE
LD (IX-10),0
JR C,LIST_NUMBER
LD (IX-8),1
JR NZ,LIST_NUMBER
LD (IX-10),1
LIST_NUMBER:
CALL SYSTEM_WORD
LD A,32
LD D,A
LD A,(IX-7)
CP 2
LD A,D
JR NZ,LIST_SEPARATOR
LD D,A
LD A,(IX-10)
OR A
LD A,D
JR Z,LIST_SEPARATOR
LD A,'>'
LIST_SEPARATOR:
RST $10
LD L,(IX-4)
LD H,(IX-3)
LIST_CHARACTER:
LD E,(IX-6)
LD D,(IX-5)
PUSH HL
OR A
SBC HL,DE
POP HL
JR NC,LIST_NEXT_LINE
LD A,(HL)
INC HL
CP 14
JR NZ,LIST_OUTPUT
LD DE,5
ADD HL,DE
JR LIST_CHARACTER
LIST_OUTPUT:
RST $10
JR LIST_CHARACTER
LIST_NEXT_LINE:
LD L,(IX-6)
LD H,(IX-5)
JP LIST_LINE
LIST_RETURN:
LD A,(IX-7)
CP 2
JR NZ,LIST_RETURN_FRAME
LD A,(IX-9)
LD ($5c8c),A
LIST_RETURN_FRAME:
LD SP,IX
POP IX
RET
; Centre the selected native line approximately ten programme records below
; the top. Rendering still uses public channels and may wrap long records.
SYSTEM_AUTO_LIST:
LD A,2
CALL CHANNEL_OPEN
CALL SCREEN_CLEAR
LD A,($5c8c)
LD (IX-9),A
LD A,255
LD ($5c8c),A
LD (IX-8),0
LD HL,(PROG)
LD BC,0
SYSTEM_AUTO_COUNT:
LD DE,($5c4b)
PUSH HL
OR A
SBC HL,DE
POP HL
JR NC,SYSTEM_AUTO_COUNTED
LD D,(HL)
INC HL
LD E,(HL)
DEC HL
PUSH HL
LD HL,($5c49)
OR A
SBC HL,DE
POP HL
JR C,SYSTEM_AUTO_COUNTED
JR Z,SYSTEM_AUTO_COUNTED
CALL SYSTEM_AUTO_NEXT
INC BC
JR SYSTEM_AUTO_COUNT
SYSTEM_AUTO_COUNTED:
LD H,B
LD L,C
LD DE,10
OR A
SBC HL,DE
JR NC,SYSTEM_AUTO_INDEX
LD HL,0
SYSTEM_AUTO_INDEX:
LD B,H
LD C,L
LD HL,(PROG)
SYSTEM_AUTO_START:
LD A,B
OR C
JR Z,SYSTEM_AUTO_READY
CALL SYSTEM_AUTO_NEXT
DEC BC
JR SYSTEM_AUTO_START
SYSTEM_AUTO_READY:
LD DE,($5c4b)
PUSH HL
OR A
SBC HL,DE
POP HL
JP NC,LIST_RETURN
LD B,(HL)
INC HL
LD C,(HL)
DEC HL
LD ($5c6c),BC
LD (IX-2),C
LD (IX-1),B
JP LIST_LINE
SYSTEM_AUTO_NEXT:
INC HL
INC HL
LD E,(HL)
INC HL
LD D,(HL)
INC HL
ADD HL,DE
RET
SYSTEM_WORD:
PUSH IY
LD H,B
LD L,C
LD IY,SYSTEM_DIVISORS
LD BC,$0005
SYSTEM_WORD_DIGIT:
LD E,(IY+0)
LD D,(IY+1)
INC IY
INC IY
LD A,'0'-1
SYSTEM_WORD_SUBTRACT:
INC A
OR A
SBC HL,DE
JR NC,SYSTEM_WORD_SUBTRACT
ADD HL,DE
CP '0'
JR NZ,SYSTEM_WORD_PRINT
LD E,A
LD A,B
OR A
LD A,E
JR NZ,SYSTEM_WORD_PRINT
DEC C
JR Z,SYSTEM_WORD_LAST
INC C
JR SYSTEM_WORD_NEXT
SYSTEM_WORD_LAST:
INC C
SYSTEM_WORD_PRINT:
RST $10
LD B,1
SYSTEM_WORD_NEXT:
DEC C
JR NZ,SYSTEM_WORD_DIGIT
POP IY
RET
SYSTEM_DIVISORS:
DW 10000,1000,100,10,1
SYSTEM_REPORT:
LD HL,($5c61)
LD (STKBOT),HL
LD (STKEND),HL
LD A,13
RST $10
LD A,(ERR_NR)
INC A
CP 28
JR C,SYSTEM_REPORT_VALID
LD A,12
SYSTEM_REPORT_VALID:
PUSH AF
CP 10
JR C,SYSTEM_REPORT_DIGIT
ADD A,7
SYSTEM_REPORT_DIGIT:
ADD A,'0'
RST $10
LD A,32
RST $10
POP AF
LD HL,REPORT_WORDS
SYSTEM_REPORT_FIND:
OR A
JR Z,SYSTEM_REPORT_TEXT
LD B,A
SYSTEM_REPORT_SKIP:
LD A,(HL)
INC HL
OR A
JR NZ,SYSTEM_REPORT_SKIP
LD A,B
DEC A
JR SYSTEM_REPORT_FIND
SYSTEM_REPORT_TEXT:
CALL PRINT_TEXT
LD A,','
RST $10
LD BC,($5c45)
BIT 7,B
JR Z,SYSTEM_REPORT_LINE
LD BC,0
SYSTEM_REPORT_LINE:
CALL SYSTEM_WORD
LD A,':'
RST $10
LD A,($5c47)
LD C,A
LD B,0
CALL SYSTEM_WORD
LD A,13
RST $10
RET
