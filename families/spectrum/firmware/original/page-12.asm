; Original user-defined functions. Active argument records have native spelling
; and five-byte payloads, in checked temporary workspace addressed by DEFADD.
MAIN_PROMPT EQU $2000
FN_ENTRY:
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$ffd0
ADD HL,SP
LD SP,HL
LD (IX-1),A
LD (IX-2),C
CALL CHECK_STACK
OR A
JP NZ,FN_LOOKUP
CALL GET_CHAR
CALL FN_NAME
LD (IX-2),C
CP '('
JP NZ,FN_SYNTAX
INC HL
LD (CH_ADD),HL
CALL FN_FIND
LD (IX-6),L
LD (IX-5),H
LD (IX-3),0
CALL FN_SPACE
CP ')'
JR Z,FN_SIGNATURE_END
FN_SIGNATURE:
CALL FN_PARAMETER
INC (IX-3)
JP Z,OUT_OF_MEMORY
CP ')'
JR Z,FN_SIGNATURE_END
CP ','
JP NZ,FN_SYNTAX
INC HL
JR FN_SIGNATURE
FN_SIGNATURE_END:
INC HL
CALL FN_SPACE
CP '='
JP NZ,FN_SYNTAX
INC HL
LD (IX-8),L
LD (IX-7),H
LD HL,($5c0b)
LD (IX-14),L
LD (IX-13),H
LD L,(IX-3)
LD H,0
LD E,L
LD D,H
ADD HL,HL
ADD HL,HL
ADD HL,HL
ADD HL,DE
INC HL
LD B,H
LD C,L
LD HL,(STKBOT)
CALL CREATE_TEMP
LD (IX-12),L
LD (IX-11),H
LD (IX-10),L
LD (IX-9),H
LD A,(IX-3)
LD (IX-4),A
OR A
JP Z,FN_ARGUMENTS_END
FN_ARGUMENT:
LD L,(IX-6)
LD H,(IX-5)
CALL FN_PARAMETER
INC HL
LD (IX-6),L
LD (IX-5),H
LD (IX-21),C
CALL GET_CHAR
CP ')'
JP Z,FN_PARAMETER_ERROR
CP ','
JP Z,FN_PARAMETER_ERROR
CALL EXPRESSION
LD A,(FLAGS)
AND 64
LD B,A
BIT 7,(IX-21)
JR Z,FN_NUMERIC_ARGUMENT
LD A,B
OR A
JP NZ,FN_PARAMETER_ERROR
JR FN_ARGUMENT_TYPE_OK
FN_NUMERIC_ARGUMENT:
LD A,B
OR A
JP Z,FN_PARAMETER_ERROR
FN_ARGUMENT_TYPE_OK:
CALL STACK_DROP
PUSH HL
LD E,(IX-10)
LD D,(IX-9)
LD A,(IX-21)
AND $7f
LD (DE),A
INC DE
BIT 7,(IX-21)
JR Z,FN_ARGUMENT_MARKER
LD A,'$'
LD (DE),A
INC DE
FN_ARGUMENT_MARKER:
LD A,14
LD (DE),A
INC DE
POP HL
LD BC,5
LDIR
LD A,','
LD (DE),A
INC DE
LD (IX-10),E
LD (IX-9),D
DEC (IX-4)
JR Z,FN_ARGUMENTS_END
CALL GET_CHAR
CP ','
JP NZ,FN_PARAMETER_ERROR
CALL NEXT_CHAR
JR FN_ARGUMENT
FN_ARGUMENTS_END:
CALL GET_CHAR
CP ')'
JP NZ,FN_PARAMETER_ERROR
CALL NEXT_CHAR
LD HL,(CH_ADD)
LD (IX-16),L
LD (IX-15),H
LD L,(IX-10)
LD H,(IX-9)
LD A,(IX-3)
OR A
JR Z,FN_BINDING_END
DEC HL
FN_BINDING_END:
LD (HL),13
LD L,(IX-12)
LD H,(IX-11)
LD ($5c0b),HL
LD L,(IX-8)
LD H,(IX-7)
LD (CH_ADD),HL
CALL EXPRESSION
CALL GET_CHAR
CP 13
JR Z,FN_RESULT
CP ':'
JP NZ,FN_SYNTAX
FN_RESULT:
LD A,(FLAGS)
AND 64
LD B,A
BIT 7,(IX-2)
JR Z,FN_NUMERIC_RESULT
LD A,B
OR A
JP NZ,FN_SYNTAX
JR FN_RESULT_TYPE_OK
FN_NUMERIC_RESULT:
LD A,B
OR A
JP Z,FN_SYNTAX
FN_RESULT_TYPE_OK:
LD L,(IX-16)
LD H,(IX-15)
LD (CH_ADD),HL
LD L,(IX-14)
LD H,(IX-13)
LD ($5c0b),HL
FN_RETURN:
LD SP,IX
POP IX
RET
FN_SPACE:
LD A,(HL)
CP 32
RET NZ
INC HL
JR FN_SPACE
FN_NAME:
CALL FN_SPACE
OR $20
CP 'a'
JP C,FN_SYNTAX
CP 'z'+1
JP NC,FN_SYNTAX
LD C,A
INC HL
CALL FN_SPACE
CP '$'
RET NZ
SET 7,C
INC HL
JP FN_SPACE
FN_PARAMETER:
CALL FN_NAME
CP 14
RET NZ
LD DE,6
ADD HL,DE
JP FN_SPACE

FN_FIND:
LD HL,(PROG)
FN_FIND_LINE:
LD DE,($5c4b)
PUSH HL
OR A
SBC HL,DE
POP HL
JP NC,FN_NOT_DEFINED
INC HL
INC HL
LD E,(HL)
INC HL
LD D,(HL)
INC HL
PUSH HL
ADD HL,DE
LD (IX-20),L
LD (IX-19),H
POP HL
LD B,0
FN_FIND_BYTE:
LD A,(HL)
CP 34
JR Z,FN_FIND_QUOTE
LD A,B
OR A
JR NZ,FN_FIND_ADVANCE
LD A,(HL)
CP 14
JR Z,FN_FIND_NUMBER
CP 234
JR Z,FN_FIND_FOLLOWING
CP 206
JR Z,FN_FIND_CANDIDATE
FN_FIND_ADVANCE:
INC HL
FN_FIND_LIMIT:
LD E,(IX-20)
LD D,(IX-19)
PUSH HL
OR A
SBC HL,DE
POP HL
JR C,FN_FIND_BYTE
FN_FIND_FOLLOWING:
LD L,(IX-20)
LD H,(IX-19)
JR FN_FIND_LINE
FN_FIND_QUOTE:
LD A,B
XOR 1
LD B,A
JR FN_FIND_ADVANCE
FN_FIND_NUMBER:
LD DE,6
ADD HL,DE
JR FN_FIND_LIMIT
FN_FIND_CANDIDATE:
PUSH HL
INC HL
CALL FN_NAME
CP '('
JP NZ,FN_SYNTAX
LD A,C
CP (IX-2)
JR Z,FN_FOUND
POP HL
LD B,0
JR FN_FIND_ADVANCE
FN_FOUND:
POP DE
INC HL
RET

FN_LOOKUP:
LD HL,($5c0b)
LD A,H
OR L
JR Z,FN_LOOKUP_MISSING
LD B,0
FN_LOOKUP_PARAMETER:
CALL FN_SPACE
CP 13
JR Z,FN_LOOKUP_MISSING
PUSH BC
CALL FN_NAME
CP 14
JP NZ,FN_SYNTAX
INC HL
LD A,C
CP (IX-2)
JR Z,FN_LOOKUP_FOUND
POP BC
LD DE,5
ADD HL,DE
CALL FN_SPACE
CP 13
JR Z,FN_LOOKUP_MISSING
CP ','
JP NZ,FN_SYNTAX
INC HL
DJNZ FN_LOOKUP_PARAMETER
JP FN_SYNTAX
FN_LOOKUP_FOUND:
POP BC
CALL PUSH_VALUE
LD BC,1
CALL PUSH_INTEGER
JP FN_RETURN
FN_LOOKUP_MISSING:
LD BC,0
CALL PUSH_INTEGER
JP FN_RETURN
FN_NOT_DEFINED:
LD A,24
JR FN_ERROR
FN_PARAMETER_ERROR:
LD A,25
JR FN_ERROR
FN_SYNTAX:
LD A,11
FN_ERROR:
LD (ERR_NR),A
JP REPORT_ERROR
