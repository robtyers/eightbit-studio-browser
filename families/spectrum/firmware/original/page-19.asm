; Checked native programme/variable MERGE. The incoming tape remains staged after
; live workspace; source positions are offsets so every insertion can relocate it.
MAIN_PROMPT EQU $2000
MERGE_ENTRY:
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$ffc0
ADD HL,SP
LD SP,HL
LD (IX-2),C
LD (IX-1),B
LD (IX-4),E
LD (IX-3),D
CALL CHECK_STACK
LD (IX-10),1
LD HL,0
LD (IX-6),L
LD (IX-5),H
LD (IX-8),L
LD (IX-7),H
; Validate the complete incoming shape before changing a live programme record.
MERGE_VALIDATE_LINE:
CALL MERGE_SOURCE
LD E,(IX-4)
LD D,(IX-3)
CALL MERGE_OFFSET_COMPARE
JP Z,MERGE_VALIDATE_VARIABLES
JP NC,MERGE_BAD
CALL MERGE_LINE_SIZE
LD A,(HL)
LD D,A
INC HL
LD E,(HL)
DEC HL
PUSH BC
LD C,(IX-8)
LD B,(IX-7)
PUSH HL
LD H,D
LD L,E
OR A
SBC HL,BC
POP HL
POP BC
JP C,MERGE_BAD
JP Z,MERGE_BAD
LD (IX-8),E
LD (IX-7),D
CALL MERGE_ADVANCE
JP MERGE_VALIDATE_LINE
MERGE_VALIDATE_VARIABLES:
CALL MERGE_SOURCE
LD E,(IX-2)
LD D,(IX-1)
CALL MERGE_OFFSET_COMPARE
JP Z,MERGE_APPLY_START
JP NC,MERGE_BAD
CALL MERGE_RECORD_SIZE
CALL MERGE_ADVANCE
JP MERGE_VALIDATE_VARIABLES
MERGE_APPLY_START:
LD HL,0
LD (IX-6),L
LD (IX-5),H
LD (IX-9),0
MERGE_APPLY_LINE:
CALL MERGE_SOURCE
LD E,(IX-4)
LD D,(IX-3)
CALL MERGE_OFFSET_COMPARE
JP Z,MERGE_APPLY_VARIABLES
CALL MERGE_LINE_SIZE
LD (IX-12),C
LD (IX-11),B
LD A,(HL)
LD (IX-14),A
INC HL
LD A,(HL)
LD (IX-13),A
LD (IX-10),0
LD HL,(PROG)
MERGE_FIND_LINE:
LD DE,($5c4b)
PUSH HL
OR A
SBC HL,DE
POP HL
JP NC,MERGE_NEW_LINE
LD A,(HL)
CP (IX-14)
JP C,MERGE_FIND_NEXT_LINE
JP NZ,MERGE_NEW_LINE
INC HL
LD A,(HL)
DEC HL
CP (IX-13)
JP C,MERGE_FIND_NEXT_LINE
JP NZ,MERGE_NEW_LINE
CALL MERGE_LINE_SIZE
JP MERGE_REPLACE_LINE
MERGE_FIND_NEXT_LINE:
CALL MERGE_LINE_SIZE
ADD HL,BC
JP MERGE_FIND_LINE
MERGE_NEW_LINE:
LD BC,0
MERGE_REPLACE_LINE:
CALL MERGE_REPLACE
LD C,(IX-12)
LD B,(IX-11)
CALL MERGE_ADVANCE
LD (IX-10),1
JP MERGE_APPLY_LINE
MERGE_APPLY_VARIABLES:
LD (IX-9),1
MERGE_APPLY_VARIABLE:
CALL MERGE_SOURCE
LD E,(IX-2)
LD D,(IX-1)
CALL MERGE_OFFSET_COMPARE
JP Z,MERGE_DONE
CALL MERGE_RECORD_SIZE
LD (IX-12),C
LD (IX-11),B
LD A,(HL)
AND $7f
LD (IX-14),A
LD HL,($5c4b)
MERGE_FIND_VARIABLE:
LD A,(HL)
CP $80
JP Z,MERGE_NEW_VARIABLE
AND $7f
CP (IX-14)
JP NZ,MERGE_FIND_NEXT_VARIABLE
AND $e0
CP $20
JP NZ,MERGE_VARIABLE_FOUND
; A long numeric name includes all its following high-bit-terminated letters.
PUSH HL
CALL MERGE_SOURCE
INC HL
EX DE,HL
POP HL
PUSH HL
INC HL
MERGE_COMPARE_NAME:
LD A,(DE)
CP (HL)
JP NZ,MERGE_NAME_DIFFERENT
INC HL
INC DE
BIT 7,A
JP Z,MERGE_COMPARE_NAME
POP HL
JP MERGE_VARIABLE_FOUND
MERGE_NAME_DIFFERENT:
POP HL
MERGE_FIND_NEXT_VARIABLE:
CALL MERGE_RECORD_SIZE
ADD HL,BC
JP MERGE_FIND_VARIABLE
MERGE_VARIABLE_FOUND:
CALL MERGE_RECORD_SIZE
JP MERGE_REPLACE_VARIABLE
MERGE_NEW_VARIABLE:
LD BC,0
MERGE_REPLACE_VARIABLE:
CALL MERGE_REPLACE
LD C,(IX-12)
LD B,(IX-11)
CALL MERGE_ADVANCE
JP MERGE_APPLY_VARIABLE
MERGE_DONE:
LD HL,0
LD ($5c57),HL
LD SP,IX
POP IX
RET
MERGE_SOURCE:
LD HL,(STKBOT)
LD C,(IX-2)
LD B,(IX-1)
OR A
SBC HL,BC
LD C,(IX-6)
LD B,(IX-5)
ADD HL,BC
RET
MERGE_OFFSET_COMPARE:
PUSH HL
LD L,(IX-6)
LD H,(IX-5)
OR A
SBC HL,DE
POP HL
RET
MERGE_ADVANCE:
LD L,(IX-6)
LD H,(IX-5)
ADD HL,BC
JP C,MERGE_BAD
LD (IX-6),L
LD (IX-5),H
RET
MERGE_REPLACE:
LD (IX-16),L
LD (IX-15),H
LD DE,(PROG)
LD (IX-18),E
LD (IX-17),D
LD DE,($5c4b)
LD (IX-20),E
LD (IX-19),D
PUSH HL
LD L,(IX-12)
LD H,(IX-11)
OR A
SBC HL,BC
POP DE
JP C,MERGE_SHRINK
LD A,H
OR L
JP Z,MERGE_WRITE
PUSH HL
LD H,D
LD L,E
ADD HL,BC
POP BC
CALL MAKE_ROOM
JP MERGE_WRITE
MERGE_SHRINK:
PUSH DE
LD DE,0
EX DE,HL
OR A
SBC HL,DE
LD B,H
LD C,L
POP HL
LD E,(IX-12)
LD D,(IX-11)
ADD HL,DE
CALL RECLAIM_SPACE
MERGE_WRITE:
LD L,(IX-18)
LD H,(IX-17)
LD (PROG),HL
LD A,(IX-9)
OR A
JP Z,MERGE_WRITE_BYTES
LD L,(IX-20)
LD H,(IX-19)
LD ($5c4b),HL
MERGE_WRITE_BYTES:
CALL MERGE_SOURCE
LD E,(IX-16)
LD D,(IX-15)
LD C,(IX-12)
LD B,(IX-11)
LDIR
RET
MERGE_LINE_SIZE:
PUSH HL
LD A,(IX-10)
OR A
LD DE,($5c4b)
JR Z,MERGE_LINE_LIMIT
LD HL,(STKBOT)
LD C,(IX-2)
LD B,(IX-1)
OR A
SBC HL,BC
LD C,(IX-4)
LD B,(IX-3)
ADD HL,BC
EX DE,HL
MERGE_LINE_LIMIT:
POP HL
PUSH HL
LD BC,4
ADD HL,BC
JP C,MERGE_BAD
OR A
SBC HL,DE
JP C,MERGE_LINE_HEADER_OK
JP NZ,MERGE_BAD
MERGE_LINE_HEADER_OK:
POP HL
PUSH HL
LD A,(HL)
CP 39
JR C,MERGE_LINE_NUMBER_OK
JP NZ,MERGE_BAD
INC HL
LD A,(HL)
DEC HL
CP 16
JP NC,MERGE_BAD
LD A,(HL)
MERGE_LINE_NUMBER_OK:
LD B,A
INC HL
LD C,(HL)
LD A,B
OR C
JP Z,MERGE_BAD
INC HL
LD C,(HL)
INC HL
LD B,(HL)
LD A,B
OR C
JP Z,MERGE_BAD
LD A,B
CP 16
JR C,MERGE_LINE_BODY_OK
JP NZ,MERGE_BAD
LD A,C
OR A
JP NZ,MERGE_BAD
MERGE_LINE_BODY_OK:
INC HL
ADD HL,BC
JP C,MERGE_BAD
PUSH HL
OR A
SBC HL,DE
POP HL
JP C,MERGE_LINE_END_OK
JP NZ,MERGE_BAD
MERGE_LINE_END_OK:
DEC HL
LD A,(HL)
CP 13
JP NZ,MERGE_BAD
INC BC
INC BC
INC BC
INC BC
POP HL
RET
MERGE_RECORD_SIZE:
PUSH HL
LD A,(HL)
AND 31
CP 1
JP C,MERGE_BAD
CP 27
JP NC,MERGE_BAD
LD A,(HL)
AND $e0
CP $60
LD BC,6
JP Z,MERGE_RECORD_END
CP $e0
LD BC,19
JP Z,MERGE_RECORD_END
CP $a0
JP Z,MERGE_LONG_SIZE
CP $40
JP Z,MERGE_LENGTH_SIZE
CP $80
JP Z,MERGE_LENGTH_SIZE
CP $c0
JP NZ,MERGE_BAD
MERGE_LENGTH_SIZE:
INC HL
LD C,(HL)
INC HL
LD B,(HL)
LD A,B
CP $ff
JP Z,MERGE_BAD
INC BC
INC BC
INC BC
JP MERGE_RECORD_END
MERGE_LONG_SIZE:
INC HL
LD BC,6
MERGE_LONG_NEXT:
LD A,(HL)
INC HL
INC BC
BIT 7,A
JP NZ,MERGE_RECORD_END
LD A,B
CP 16
JP NC,MERGE_BAD
JP MERGE_LONG_NEXT
MERGE_RECORD_END:
POP HL
PUSH HL
LD DE,(E_LINE)
OR A
SBC HL,DE
POP HL
JR NC,MERGE_RECORD_STAGED_END
DEC DE
JR MERGE_RECORD_LIMIT
MERGE_RECORD_STAGED_END:
LD DE,(STKBOT)
MERGE_RECORD_LIMIT:
PUSH HL
ADD HL,BC
JP C,MERGE_BAD
OR A
SBC HL,DE
POP HL
JP C,MERGE_RECORD_VALID
JP NZ,MERGE_BAD
MERGE_RECORD_VALID:
LD A,(HL)
AND $e0
CP $80
JR Z,MERGE_RECORD_ARRAY
CP $c0
RET NZ
MERGE_RECORD_ARRAY:
PUSH BC
PUSH HL
LD A,(HL)
AND $e0
LD B,3
CP $80
JR Z,MERGE_RECORD_ARRAY_KIND
INC B
MERGE_RECORD_ARRAY_KIND:
INC HL
LD E,(HL)
INC HL
LD D,(HL)
INC HL
CALL ARRAY_FILE_VALIDATE
POP HL
POP BC
RET
MERGE_BAD:
LD A,26
LD (ERR_NR),A
