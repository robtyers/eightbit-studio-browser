LD IX,0
ADD IX,SP
LD HL,$fff0
ADD HL,SP
LD SP,HL
LD HL,($5c61)
LD (IX-2),L
LD (IX-1),H
LD DE,(E_LINE)
OR A
SBC HL,DE
JP C,OUT_OF_MEMORY
LD A,H
OR L
JP Z,OUT_OF_MEMORY
LD (IX-4),L
LD (IX-3),H
LD B,H
LD C,L
LD L,(IX-2)
LD H,(IX-1)
CALL MAKE_ROOM
LD HL,(E_LINE)
LD E,(IX-2)
LD D,(IX-1)
LD C,(IX-4)
LD B,(IX-3)
LDIR
LD L,(IX-2)
LD H,(IX-1)
LD A,2
CALL TOKEN_ACCESS
LD L,(IX-2)
LD H,(IX-1)
XOR A
CALL SYNTAX_ENTRY
PUSH AF
POP BC
LD (IX-6),C
LD (IX-5),B
LD L,(IX-2)
LD H,(IX-1)
LD C,(IX-4)
LD B,(IX-3)
CALL RECLAIM_SPACE
LD HL,(E_LINE)
LD (CH_ADD),HL
LD HL,($5c61)
DEC HL
LD C,(IX-6)
LD B,(IX-5)
PUSH BC
POP AF
LD SP,IX
POP IX
RET
