; BASIC BEEP conversion is original guest floating-point code.
MAIN_PROMPT EQU $2000
SOUND_ENTRY:
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$ffe0
ADD HL,SP
LD SP,HL
CALL CHECK_STACK
LD A,$f6
CALL SOUND_STORE
LD A,$f1
CALL SOUND_STORE
BIT 7,(IX-14)
JP NZ,SOUND_RANGE
CALL SOUND_PITCH
LD BC,60
CALL PUSH_INTEGER
LD A,4
CALL FP_OPERATION
LD A,17
CALL FP_OPERATION
CALL SOUND_BOOL
JP NZ,SOUND_RANGE
CALL SOUND_PITCH
LD BC,69
CALL PUSH_INTEGER
LD A,18
CALL FP_OPERATION
CALL SOUND_BOOL
JP NZ,SOUND_RANGE
CALL SOUND_PITCH
LD BC,12
CALL PUSH_INTEGER
LD A,3
CALL FP_OPERATION
LD HL,SOUND_LOG_TWO
CALL PUSH_NUMBER
LD A,2
CALL FP_OPERATION
LD A,39
CALL FP_OPERATION
LD HL,SOUND_MIDDLE_C
CALL PUSH_NUMBER
LD A,2
CALL FP_OPERATION
LD A,$f6
CALL SOUND_STORE
CALL SOUND_PITCH
LD A,$f1
CALL SOUND_LOAD
LD A,2
CALL FP_OPERATION
LD A,7
CALL FP_OPERATION
LD A,8
CALL FP_OPERATION
CALL SOUND_WORD
LD (IX-18),C
LD (IX-17),B
LD HL,SOUND_CLOCK_DIVISOR
CALL PUSH_NUMBER
CALL SOUND_PITCH
LD A,3
CALL FP_OPERATION
LD HL,SOUND_DELAY_OFFSET
CALL PUSH_NUMBER
LD A,1
CALL FP_OPERATION
LD A,7
CALL FP_OPERATION
LD A,8
CALL FP_OPERATION
CALL SOUND_WORD
LD H,B
LD L,C
LD E,(IX-18)
LD D,(IX-17)
CALL BEEPER
LD SP,IX
POP IX
RET
SOUND_PITCH:
LD A,$f6
SOUND_LOAD:
LD E,A
LD D,$ff
PUSH IX
POP HL
ADD HL,DE
JP PUSH_NUMBER
SOUND_STORE:
LD E,A
LD D,$ff
PUSH DE
CALL STACK_DROP
POP DE
PUSH HL
PUSH IX
POP HL
ADD HL,DE
EX DE,HL
POP HL
LD BC,5
LDIR
RET
SOUND_WORD:
CALL STACK_DROP
INC HL
INC HL
LD C,(HL)
INC HL
LD B,(HL)
RET
SOUND_BOOL:
CALL STACK_DROP
LD A,(HL)
OR A
RET
SOUND_RANGE:
LD A,10
LD (ERR_NR),A
JP REPORT_ERROR
SOUND_LOG_TWO:
DB 128,49,114,23,248
SOUND_MIDDLE_C:
DB 137,2,208,18,134
SOUND_CLOCK_DIVISOR:
DB 147,85,159,128,0
SOUND_DELAY_OFFSET:
DB 133,113,0,0,0
