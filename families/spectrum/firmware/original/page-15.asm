; The stock printer is absent. Its standard buffer/cursor still have native RAM
; semantics; completed lines are discarded without any host peripheral access.
MAIN_PROMPT EQU $2000
PRINTER_ENTRY:
PUSH AF
CALL MODEL_128
JR Z,PRINTER_48_ENTRY
; The 128K serial printer has no attached peripheral. Do not reuse its system
; variable area as the 48K printer bitmap buffer.
POP AF
RET
PRINTER_48_ENTRY:
POP AF
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$fff0
ADD HL,SP
LD SP,HL
LD (IX-1),A
CALL CHECK_STACK
LD A,(TVDATA)
OR A
JP NZ,PRINTER_CONTROL
LD A,(IX-1)
CP 6
JP Z,PRINTER_COMMA
CP 13
JP Z,PRINTER_FLUSH
CP 16
JP C,PRINTER_RETURN
CP 24
JP NC,PRINTER_GLYPH
LD (TVDATA),A
JP PRINTER_RETURN
PRINTER_CONTROL:
LD B,A
XOR A
LD (TVDATA),A
LD A,B
CP 22
JP Z,PRINTER_AT_ROW
CP $96
JP Z,PRINTER_AT_COLUMN
CP 23
JP Z,PRINTER_TAB_LOW
CP $97
JP Z,PRINTER_TAB_COLUMN
CP 20
JP C,PRINTER_RETURN
CP 22
JP NC,PRINTER_RETURN
LD C,(IX-1)
CALL COLOUR_ACCESS
JP PRINTER_RETURN
PRINTER_AT_ROW:
LD A,$96
LD (TVDATA),A
JP PRINTER_RETURN
PRINTER_AT_COLUMN:
LD A,(IX-1)
CP 32
JP NC,PRINTER_SCREEN_ERROR
LD L,A
LD H,$5b
LD ($5c80),HL
LD C,A
LD A,33
SUB C
LD ($5c7f),A
JP PRINTER_RETURN
PRINTER_TAB_LOW:
LD A,(IX-1)
AND 31
LD (TVDATA+1),A
LD A,$97
LD (TVDATA),A
JP PRINTER_RETURN
PRINTER_TAB_COLUMN:
LD A,(TVDATA+1)
LD B,A
LD A,33
SUB B
LD (IX-2),A
PRINTER_TAB_SPACE:
LD A,($5c7f)
CP (IX-2)
JP Z,PRINTER_RETURN
LD A,32
RST $10
JP PRINTER_TAB_SPACE
PRINTER_GLYPH:
CP 32
JP C,PRINTER_RETURN
CALL TOKEN_BYTE
JP NC,PRINTER_TOKEN
PUSH AF
LD A,($5c7f)
CP 1
CALL Z,PRINTER_CLEAR_BUFFER
POP AF
CP 128
JP NC,PRINTER_GRAPHIC
LD L,A
LD H,0
ADD HL,HL
ADD HL,HL
ADD HL,HL
LD DE,(CHARS)
ADD HL,DE
JP PRINTER_PATTERN
PRINTER_GRAPHIC:
CP 144
JP NC,PRINTER_UDG
SUB 128
LD DE,BLOCK_GLYPHS
JP PRINTER_GRAPHIC_ADDRESS
PRINTER_UDG:
SUB 144
LD DE,(UDG)
PRINTER_GRAPHIC_ADDRESS:
LD L,A
LD H,0
ADD HL,HL
ADD HL,HL
ADD HL,HL
ADD HL,DE
PRINTER_PATTERN:
LD DE,($5c80)
LD B,8
PRINTER_PATTERN_ROW:
LD A,(P_FLAG)
LD C,A
LD A,(HL)
BIT 2,C
JP Z,PRINTER_NOT_INVERSE
CPL
PRINTER_NOT_INVERSE:
BIT 0,C
JP Z,PRINTER_WRITE
LD C,A
LD A,(DE)
XOR C
PRINTER_WRITE:
LD (DE),A
PUSH HL
LD HL,32
ADD HL,DE
EX DE,HL
POP HL
INC HL
DJNZ PRINTER_PATTERN_ROW
LD HL,($5c80)
INC HL
LD ($5c80),HL
LD HL,$5c7f
DEC (HL)
PRINTER_RETURN:
LD SP,IX
POP IX
RET
PRINTER_TOKEN:
LD C,A
LD A,1
CALL TOKEN_ACCESS
JP PRINTER_RETURN
PRINTER_COMMA:
LD A,($5c7f)
CP 18
JP C,PRINTER_COMMA_WRAP
PRINTER_COMMA_FIRST:
LD A,32
RST $10
LD A,($5c7f)
CP 17
JP NZ,PRINTER_COMMA_FIRST
JP PRINTER_RETURN
PRINTER_COMMA_WRAP:
LD A,($5c7f)
CP 1
JP Z,PRINTER_FLUSH
LD A,32
RST $10
JP PRINTER_COMMA_WRAP
PRINTER_FLUSH:
CALL PRINTER_CLEAR_BUFFER
JP PRINTER_RETURN
PRINTER_CLEAR_BUFFER:
LD HL,$5b00
LD ($5c80),HL
LD DE,$5b01
LD BC,255
LD (HL),0
LDIR
LD A,33
LD ($5c7f),A
RET
PRINTER_SCREEN_ERROR:
LD A,4
LD (ERR_NR),A
JP REPORT_ERROR
