ADD HL,HL
INC HL
ADD HL,DE
LD (IX-15),L
LD (IX-14),H
LD A,(IX-8)
CP (IX-9)
JR NC,GRAPH_CIRCLE_NEXT
GRAPH_CIRCLE_FINISH:
LD A,(IX-2)
ADD A,(IX-6)
LD ($5c7d),A
LD A,(IX-3)
LD ($5c7e),A
