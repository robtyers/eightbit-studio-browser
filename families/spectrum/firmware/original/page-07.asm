LD A,(IX-3)
SUB (IX-6)
JP C,GRAPH_RANGE
LD A,(IX-3)
ADD A,(IX-6)
JP C,GRAPH_RANGE
CP 176
JP NC,GRAPH_RANGE
LD (IX-9),0
LD L,(IX-6)
LD H,0
EX DE,HL
LD HL,1
OR A
SBC HL,DE
LD (IX-15),L
LD (IX-14),H
GRAPH_CIRCLE_NEXT:
LD D,(IX-8)
LD E,(IX-9)
CALL GRAPH_CIRCLE_PAIR
LD A,(IX-6)
OR A
JR Z,GRAPH_CIRCLE_FINISH
LD A,(IX-8)
