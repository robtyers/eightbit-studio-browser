; Original pixel/attribute primitives. B,C carry row/column or y/x respectively.
MAIN_PROMPT EQU $2000
GRAPH_ENTRY:
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$ffe8
ADD HL,SP
LD SP,HL
LD (IX-1),A
LD (IX-2),C
LD (IX-3),B
CALL CHECK_STACK
CP 4
JP Z,GRAPH_LINE
CP 5
JP Z,GRAPH_CIRCLE
CP 2
JP NC,GRAPH_CELL
LD A,B
CP 176
JP NC,GRAPH_RANGE
LD A,175
SUB B
CALL PIXEL_ADDRESS
LD A,C
AND 7
LD B,A
LD A,$80
JR Z,GRAPH_MASK
GRAPH_MASK_SHIFT:
RRCA
DJNZ GRAPH_MASK_SHIFT
GRAPH_MASK:
LD (IX-4),A
LD A,C
RRCA
RRCA
RRCA
AND 31
OR E
LD E,A
LD A,(IX-1)
OR A
JR NZ,GRAPH_POINT
LD A,(IX-2)
LD ($5c7d),A
LD A,(IX-3)
LD ($5c7e),A
LD A,(P_FLAG)
BIT 0,A
JR NZ,GRAPH_XOR
BIT 2,A
JR NZ,GRAPH_ERASE
LD A,(DE)
OR (IX-4)
JR GRAPH_WRITE
GRAPH_ERASE:
LD A,(IX-4)
CPL
LD B,A
LD A,(DE)
AND B
JR GRAPH_WRITE
GRAPH_XOR:
BIT 2,A
JR NZ,GRAPH_ATTRIBUTES
LD A,(DE)
XOR (IX-4)
GRAPH_WRITE:
LD (DE),A
GRAPH_ATTRIBUTES:
LD A,175
SUB (IX-3)
RRCA
RRCA
RRCA
AND 31
LD B,A
LD A,(IX-2)
RRCA
RRCA
RRCA
AND 31
LD C,A
CALL GRAPH_ATTRIBUTE_ADDRESS
LD A,32
CALL COLOUR_ACCESS
JR GRAPH_RETURN
GRAPH_POINT:
LD A,(DE)
AND (IX-4)
LD BC,0
JR Z,GRAPH_PUSH_INTEGER
INC BC
GRAPH_PUSH_INTEGER:
CALL PUSH_INTEGER
JR GRAPH_RETURN
GRAPH_CELL:
LD A,B
CP 24
JR NC,GRAPH_RANGE
LD A,C
CP 32
JR NC,GRAPH_RANGE
CALL GRAPH_ATTRIBUTE_ADDRESS
LD C,(HL)
LD B,0
LD A,(IX-1)
CP 2
JR Z,GRAPH_PUSH_INTEGER
JP GRAPH_SCREEN
GRAPH_ATTRIBUTE_ADDRESS:
LD H,0
LD L,B
ADD HL,HL
ADD HL,HL
ADD HL,HL
ADD HL,HL
ADD HL,HL
LD B,$58
ADD HL,BC
RET
GRAPH_RETURN:
LD SP,IX
POP IX
RET
GRAPH_RANGE:
LD A,10
LD (ERR_NR),A
JP REPORT_ERROR
GRAPH_SCREEN:
LD A,(IX-3)
RLCA
RLCA
RLCA
CALL PIXEL_ADDRESS
LD A,(IX-2)
OR E
LD E,A
LD (IX-6),E
LD (IX-5),D
LD HL,(CHARS)
LD BC,256
ADD HL,BC
LD (IX-7),32
GRAPH_SCREEN_GLYPH:
LD (IX-8),2
LD E,(IX-6)
LD D,(IX-5)
LD B,8
PUSH HL
GRAPH_SCREEN_ROW:
LD A,(DE)
XOR (HL)
LD C,A
LD A,(IX-8)
CP 2
LD A,C
JR NZ,GRAPH_SCREEN_COMPARE
OR A
JR Z,GRAPH_SCREEN_POLARITY
CP 255
JR NZ,GRAPH_SCREEN_NEXT
GRAPH_SCREEN_POLARITY:
LD (IX-8),A
GRAPH_SCREEN_COMPARE:
CP (IX-8)
JR NZ,GRAPH_SCREEN_NEXT
INC D
INC HL
DJNZ GRAPH_SCREEN_ROW
POP HL
LD BC,1
LD HL,(STKBOT)
CALL CREATE_TEMP
LD A,(IX-7)
LD (HL),A
EX DE,HL
JR GRAPH_SCREEN_PUSH
GRAPH_SCREEN_NEXT:
POP HL
LD BC,8
ADD HL,BC
INC (IX-7)
BIT 7,(IX-7)
JR Z,GRAPH_SCREEN_GLYPH
LD BC,0
LD DE,(STKBOT)
GRAPH_SCREEN_PUSH:
LD HL,(STKEND)
LD (HL),0
INC HL
LD (HL),E
INC HL
LD (HL),D
INC HL
LD (HL),C
INC HL
LD (HL),B
INC HL
LD (STKEND),HL
LD HL,FLAGS
RES 6,(HL)
JP GRAPH_RETURN

; Integer rasterisation keeps the start pixel untouched, then advances to the
; inclusive end. The signed error is bounded by the physical screen dimensions.
GRAPH_LINE:
LD A,B
CP 176
JP NC,GRAPH_RANGE
LD A,($5c7d)
LD (IX-8),A
LD C,A
LD A,(IX-2)
SUB C
LD B,1
JR NC,GRAPH_LINE_DX
NEG
LD B,255
GRAPH_LINE_DX:
LD (IX-6),B
LD (IX-11),A
LD (IX-10),0
LD A,($5c7e)
LD (IX-9),A
LD C,A
LD A,(IX-3)
SUB C
LD B,1
JR NC,GRAPH_LINE_DY
NEG
LD B,255
GRAPH_LINE_DY:
LD (IX-7),B
LD (IX-13),A
LD (IX-12),0
LD L,(IX-11)
LD H,0
LD E,(IX-13)
LD D,0
OR A
SBC HL,DE
LD (IX-15),L
LD (IX-14),H
GRAPH_LINE_NEXT:
LD A,(IX-8)
CP (IX-2)
JR NZ,GRAPH_LINE_ADVANCE
LD A,(IX-9)
CP (IX-3)
JP Z,GRAPH_RETURN
GRAPH_LINE_ADVANCE:
LD L,(IX-15)
LD H,(IX-14)
ADD HL,HL
LD (IX-18),L
LD (IX-17),H
LD E,(IX-13)
LD D,0
ADD HL,DE
BIT 7,H
JR NZ,GRAPH_LINE_Y
LD A,H
OR L
JR Z,GRAPH_LINE_Y
LD L,(IX-15)
LD H,(IX-14)
OR A
SBC HL,DE
LD (IX-15),L
LD (IX-14),H
LD A,(IX-8)
ADD A,(IX-6)
LD (IX-8),A
GRAPH_LINE_Y:
LD L,(IX-18)
LD H,(IX-17)
LD E,(IX-11)
LD D,0
OR A
SBC HL,DE
BIT 7,H
JR Z,GRAPH_LINE_PLOT
LD L,(IX-15)
LD H,(IX-14)
ADD HL,DE
LD (IX-15),L
LD (IX-14),H
LD A,(IX-9)
ADD A,(IX-7)
LD (IX-9),A
GRAPH_LINE_PLOT:
LD C,(IX-8)
LD B,(IX-9)
XOR A
CALL GRAPHICS_ACCESS
JP GRAPH_LINE_NEXT

