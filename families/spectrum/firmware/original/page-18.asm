; Convert edited lines into native numeric/FN cells before replacing programme RAM.
; No old line is removed until the complete edit buffer has been encoded.
MAIN_PROMPT EQU $2000
CANONICAL_ENTRY:
PUSH IX
LD IX,0
ADD IX,SP
LD HL,$ffe0
ADD HL,SP
LD SP,HL
CALL CHECK_STACK
LD HL,(CH_ADD)
LD (IX-2),L
LD (IX-1),H
LD (IX-3),0
CANONICAL_SCAN:
LD A,(HL)
CP 13
JP Z,CANONICAL_FINISH
CP 34
JP Z,CANONICAL_QUOTE
LD A,(IX-3)
CP 1
JP Z,CANONICAL_NEXT
LD A,(HL)
CP 14
JP Z,CANONICAL_SKIP_CELL
CP 234
JP Z,CANONICAL_FINISH
CP 206
JP Z,CANONICAL_DEFINITION
LD A,(IX-3)
CP 2
JP Z,CANONICAL_IDENTIFIER
LD A,(HL)
CP 196
JP Z,CANONICAL_NUMBER
CP '.'
JP Z,CANONICAL_DOT
CP '0'
JP C,CANONICAL_LETTER
CP '9'+1
JP C,CANONICAL_NUMBER
CANONICAL_LETTER:
OR $20
CP 'a'
JP C,CANONICAL_NEXT
CP 'z'+1
JP NC,CANONICAL_NEXT
LD (IX-3),2
JP CANONICAL_NEXT
CANONICAL_IDENTIFIER:
LD A,(HL)
OR $20
CP 'a'
JP C,CANONICAL_IDENTIFIER_DIGIT
CP 'z'+1
JP C,CANONICAL_NEXT
CANONICAL_IDENTIFIER_DIGIT:
CP '0'
JP C,CANONICAL_IDENTIFIER_SPACE
CP '9'+1
JP C,CANONICAL_NEXT
CANONICAL_IDENTIFIER_SPACE:
CP 32
JP Z,CANONICAL_NEXT
CP '$'
JP Z,CANONICAL_NEXT
LD (IX-3),0
JP CANONICAL_SCAN
CANONICAL_DOT:
INC HL
LD A,(HL)
DEC HL
CP '0'
JP C,CANONICAL_NEXT
CP '9'+1
JP NC,CANONICAL_NEXT
CANONICAL_NUMBER:
LD (IX-6),L
LD (IX-5),H
CALL CANONICAL_LITERAL_END
LD A,(HL)
CP 14
JP Z,CANONICAL_SKIP_CELL
LD (IX-8),L
LD (IX-7),H
LD L,(IX-6)
LD H,(IX-5)
LD (CH_ADD),HL
LD A,1
CALL EXPRESSION_SERVICE
CALL STACK_DROP
PUSH HL
PUSH IX
POP DE
LD HL,$ffe5
ADD HL,DE
EX DE,HL
POP HL
LD BC,5
LDIR
LD L,(IX-8)
LD H,(IX-7)
CALL CANONICAL_ROOM
LD (HL),14
INC HL
EX DE,HL
PUSH IX
POP HL
LD BC,$ffe5
ADD HL,BC
LD BC,5
LDIR
EX DE,HL
JP CANONICAL_SCAN
CANONICAL_LITERAL_END:
LD A,(HL)
CP 196
JP Z,CANONICAL_BIN_END
CANONICAL_DECIMAL_END:
LD A,(HL)
CP '0'
JP C,CANONICAL_FRACTION_END
CP '9'+1
JP NC,CANONICAL_FRACTION_END
INC HL
JP CANONICAL_DECIMAL_END
CANONICAL_FRACTION_END:
CP '.'
JP NZ,CANONICAL_EXPONENT_END
INC HL
CANONICAL_FRACTION_DIGIT:
LD A,(HL)
CP '0'
JP C,CANONICAL_EXPONENT_END
CP '9'+1
JP NC,CANONICAL_EXPONENT_END
INC HL
JP CANONICAL_FRACTION_DIGIT
CANONICAL_EXPONENT_END:
AND $df
CP 'E'
RET NZ
INC HL
LD A,(HL)
CP '+'
JP Z,CANONICAL_EXPONENT_SIGN
CP '-'
JP NZ,CANONICAL_EXPONENT_DIGIT
CANONICAL_EXPONENT_SIGN:
INC HL
CANONICAL_EXPONENT_DIGIT:
LD A,(HL)
CP '0'
RET C
CP '9'+1
RET NC
INC HL
JP CANONICAL_EXPONENT_DIGIT
CANONICAL_BIN_END:
INC HL
CALL CANONICAL_SPACE
CANONICAL_BIN_DIGIT:
LD A,(HL)
CP '0'
JP Z,CANONICAL_BIN_NEXT
CP '1'
RET NZ
CANONICAL_BIN_NEXT:
INC HL
JP CANONICAL_BIN_DIGIT
CANONICAL_QUOTE:
LD A,(IX-3)
XOR 1
AND 1
LD (IX-3),A
CANONICAL_NEXT:
INC HL
JP CANONICAL_SCAN
CANONICAL_SKIP_CELL:
LD DE,6
ADD HL,DE
JP CANONICAL_SCAN
CANONICAL_DEFINITION:
INC HL
CALL CANONICAL_SPACE
; The function name and optional $ precede the argument brackets.
INC HL
CALL CANONICAL_SPACE
CP '$'
JP NZ,CANONICAL_FN_BRACKET
INC HL
CALL CANONICAL_SPACE
CANONICAL_FN_BRACKET:
CP '('
JP NZ,CANONICAL_SYNTAX
INC HL
CALL CANONICAL_SPACE
CP ')'
JP Z,CANONICAL_FN_END
CANONICAL_PARAMETER:
OR $20
CP 'a'
JP C,CANONICAL_SYNTAX
CP 'z'+1
JP NC,CANONICAL_SYNTAX
INC HL
CALL CANONICAL_SPACE
CP '$'
JP NZ,CANONICAL_PARAMETER_CELL
INC HL
CALL CANONICAL_SPACE
CANONICAL_PARAMETER_CELL:
CP 14
JP Z,CANONICAL_PARAMETER_EXISTING
CALL CANONICAL_ROOM
LD (HL),14
INC HL
LD B,5
XOR A
CANONICAL_PARAMETER_ZERO:
LD (HL),A
INC HL
DJNZ CANONICAL_PARAMETER_ZERO
JP CANONICAL_PARAMETER_NEXT
CANONICAL_PARAMETER_EXISTING:
LD DE,6
ADD HL,DE
CANONICAL_PARAMETER_NEXT:
CALL CANONICAL_SPACE
CP ')'
JP Z,CANONICAL_FN_END
CP ','
JP NZ,CANONICAL_SYNTAX
INC HL
CALL CANONICAL_SPACE
JP CANONICAL_PARAMETER
CANONICAL_FN_END:
INC HL
LD (IX-3),0
JP CANONICAL_SCAN
CANONICAL_SPACE:
LD A,(HL)
CP 32
RET NZ
INC HL
JP CANONICAL_SPACE
CANONICAL_ROOM:
PUSH HL
LD HL,($5c61)
LD E,(IX-2)
LD D,(IX-1)
OR A
SBC HL,DE
LD DE,4091
OR A
SBC HL,DE
POP HL
JP NC,CANONICAL_TOO_LONG
LD BC,6
JP MAKE_ROOM
CANONICAL_TOO_LONG:
LD A,15
LD (ERR_NR),A
JP REPORT_ERROR
CANONICAL_SYNTAX:
LD A,11
LD (ERR_NR),A
JP REPORT_ERROR
CANONICAL_FINISH:
LD L,(IX-2)
LD H,(IX-1)
LD (CH_ADD),HL
LD SP,IX
POP IX
RET
