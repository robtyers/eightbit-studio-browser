; Original cassette edge decoder. Samples the emulated EAR pin as real Z80 code.
MAIN_PROMPT EQU $2000
TAPE_ENTRY:
PUSH IY
LD IY,0
ADD IY,SP
LD HL,$ffe0
ADD HL,SP
LD SP,HL
LD (IY-1),C
LD (IY-2),B
LD (IY-6),E
LD (IY-5),D
LD A,I
PUSH AF
POP HL
LD (IY-9),L
DI
LD A,C
CP 2
JP Z,TAPE_SAVE_PROCESS
IN A,($fe)
AND $40
LD (IY-3),A
LD B,0
TAPE_PILOT:
CALL TAPE_EDGE
JR NC,TAPE_PILOT_RESTART
LD A,H
OR A
JR NZ,TAPE_PILOT_RESTART
LD A,L
CP 30
JR C,TAPE_PILOT_SHORT
CP 49
JR NC,TAPE_PILOT_RESTART
INC B
LD A,B
CP 32
JR C,TAPE_PILOT
LD B,32
JR TAPE_PILOT
TAPE_PILOT_RESTART:
LD B,0
CALL TAPE_BREAK
JR TAPE_PILOT
TAPE_PILOT_SHORT:
LD A,B
CP 32
JR C,TAPE_PILOT_RESTART
LD A,L
; Counts exclude call/qualification time. A contended 4000h-7fffh stack can
; reduce a valid 667/735 T sync pulse below eight unchanged sample iterations.
CP 6
JR C,TAPE_PILOT_RESTART
CP 19
JR NC,TAPE_PILOT_RESTART
CALL TAPE_EDGE
JR NC,TAPE_PILOT_RESTART
LD A,H
OR A
JR NZ,TAPE_PILOT_RESTART
LD A,L
CP 6
JR C,TAPE_PILOT_RESTART
CP 19
JR NC,TAPE_PILOT_RESTART
CALL TAPE_BYTE
JP NC,TAPE_FAILED
CP (IY-2)
JP NZ,TAPE_FAILED
LD (IY-4),A
TAPE_DATA:
LD E,(IY-6)
LD D,(IY-5)
LD A,D
OR E
JR Z,TAPE_CHECKSUM
CALL TAPE_BYTE
JP NC,TAPE_FAILED
LD C,A
XOR (IY-4)
LD (IY-4),A
LD A,(IY-1)
OR A
JR Z,TAPE_VERIFY
LD (IX+0),C
JR TAPE_DATA_NEXT
TAPE_VERIFY:
LD A,(IX+0)
CP C
JP NZ,TAPE_FAILED
TAPE_DATA_NEXT:
INC IX
LD E,(IY-6)
LD D,(IY-5)
DEC DE
LD (IY-6),E
LD (IY-5),D
JR TAPE_DATA
TAPE_CHECKSUM:
CALL TAPE_BYTE
JR NC,TAPE_FAILED
XOR (IY-4)
JR NZ,TAPE_FAILED
SCF
JR TAPE_RETURN
TAPE_FAILED:
OR A
TAPE_RETURN:
PUSH AF
POP BC
LD E,(IY-6)
LD D,(IY-5)
LD L,(IY-9)
LD SP,IY
POP IY
BIT 2,L
JR Z,TAPE_RETURN_DISABLED
EI
TAPE_RETURN_DISABLED:
PUSH BC
POP AF
RET

; Uncontended loop: 55 T states per unchanged sample. The first and last
; iterations contribute bounded fixed phase error, well below the pulse gap.
TAPE_EDGE:
LD D,(IY-3)
LD HL,0
TAPE_EDGE_SAMPLE:
IN A,($fe)
XOR D
AND $40
JR NZ,TAPE_EDGE_FOUND
INC HL
LD A,H
OR L
JR NZ,TAPE_EDGE_SAMPLE
OR A
RET
TAPE_EDGE_FOUND:
LD A,D
XOR $40
LD (IY-3),A
SCF
RET
TAPE_BYTE:
LD BC,$0800
TAPE_BIT:
CALL TAPE_EDGE
RET NC
LD A,H
OR A
JR NZ,TAPE_BAD_BYTE
LD E,L
CALL TAPE_EDGE
RET NC
LD A,H
OR A
JR NZ,TAPE_BAD_BYTE
LD A,L
ADD A,E
CP 46
CCF
RL C
DJNZ TAPE_BIT
LD A,C
SCF
RET
TAPE_BAD_BYTE:
OR A
RET
TAPE_BREAK:
LD A,$7f
IN A,($fe)
AND 1
RET NZ
LD A,$fe
IN A,($fe)
AND 1
RET NZ
LD A,12
LD (ERR_NR),A
JP REPORT_ERROR

TAPE_SAVE_PROCESS:
EXX
PUSH BC
EXX
LD A,($5c48)
AND $38
RRCA
RRCA
RRCA
LD (IY-3),A
OUT ($fe),A
LD A,(IY-2)
LD C,A
LD (IY-4),A
LD (IY-14),0
LD HL,8063
BIT 7,A
JR Z,TAPE_SAVE_PILOT
LD HL,3223
TAPE_SAVE_PILOT:
CALL TAPE_PULSE_PILOT
DEC HL
LD A,L
OR A
CALL Z,TAPE_BREAK
LD A,H
OR L
JP NZ,TAPE_SAVE_PILOT
CALL TAPE_PULSE_SYNC_ONE
CALL TAPE_PULSE_SYNC_TWO
LD E,(IY-6)
LD D,(IY-5)
LD A,C
CALL TAPE_SEND_BYTE
TAPE_SAVE_DATA:
LD A,D
OR E
JR Z,TAPE_SAVE_CHECKSUM
LD A,(IX+0)
INC IX
LD H,A
LD A,(IY-4)
XOR H
LD (IY-4),A
LD A,H
DEC DE
CALL TAPE_SEND_BYTE
JR TAPE_SAVE_DATA
TAPE_SAVE_CHECKSUM:
LD (IY-14),1
LD A,(IY-4)
CALL TAPE_SEND_BYTE
LD A,(IY-3)
AND $f7
LD (IY-3),A
OUT ($fe),A
EXX
POP BC
EXX
LD (IY-6),0
LD (IY-5),0
SCF
JP TAPE_RETURN

TAPE_SEND_BYTE:
LD C,A
LD B,8
TAPE_SEND_BIT:
SLA C
JP C,TAPE_SEND_ONE
LD A,B
CP 1
JR Z,TAPE_SEND_ZERO_LAST
CALL TAPE_PULSE_ZERO_FIRST
CALL TAPE_PULSE_ZERO_SECOND
JP TAPE_SEND_NEXT
TAPE_SEND_ZERO_LAST:
CALL TAPE_PULSE_ZERO_FIRST_LAST
LD A,(IY-14)
OR A
JR NZ,TAPE_SEND_ZERO_CHECKSUM
LD A,D
OR E
JR Z,TAPE_SEND_ZERO_END_DATA
CALL TAPE_PULSE_ZERO_BOUNDARY
JP TAPE_SEND_NEXT
TAPE_SEND_ZERO_END_DATA:
CALL TAPE_PULSE_ZERO_END_DATA
JP TAPE_SEND_NEXT
TAPE_SEND_ZERO_CHECKSUM:
CALL TAPE_PULSE_ZERO_END_CHECKSUM
JP TAPE_SEND_NEXT
TAPE_SEND_ONE:
LD A,B
CP 1
JR Z,TAPE_SEND_ONE_LAST
CALL TAPE_PULSE_ONE_FIRST
CALL TAPE_PULSE_ONE_SECOND
JP TAPE_SEND_NEXT
TAPE_SEND_ONE_LAST:
CALL TAPE_PULSE_ONE_FIRST_LAST
LD A,(IY-14)
OR A
JR NZ,TAPE_SEND_ONE_CHECKSUM
LD A,D
OR E
JR Z,TAPE_SEND_ONE_END_DATA
CALL TAPE_PULSE_ONE_BOUNDARY
JP TAPE_SEND_NEXT
TAPE_SEND_ONE_END_DATA:
CALL TAPE_PULSE_ONE_END_DATA
JP TAPE_SEND_NEXT
TAPE_SEND_ONE_CHECKSUM:
CALL TAPE_PULSE_ONE_END_CHECKSUM
JP TAPE_SEND_NEXT
TAPE_SEND_NEXT:
DJNZ TAPE_SEND_BIT
RET

; Timed loops use the alternate BC so byte/length ownership remains live. The
; independent pulse tests include byte boundaries and the final checksum edge.
TAPE_PULSE_PILOT:
EXX
LD BC,78
JP TAPE_PULSE_COMMON
TAPE_PULSE_SYNC_ONE:
EXX
LD BC,22
JP TAPE_PULSE_COMMON
TAPE_PULSE_SYNC_TWO:
EXX
LD BC,18
JP TAPE_PULSE_COMMON
TAPE_PULSE_ZERO_FIRST:
EXX
LD BC,28
JP TAPE_PULSE_COMMON
TAPE_PULSE_ZERO_FIRST_LAST:
EXX
LD BC,26
JP TAPE_PULSE_COMMON
TAPE_PULSE_ZERO_SECOND:
EXX
LD BC,26
JP TAPE_PULSE_COMMON
TAPE_PULSE_ZERO_BOUNDARY:
EXX
LD BC,21
JP TAPE_PULSE_COMMON
TAPE_PULSE_ZERO_END_DATA:
EXX
LD BC,23
JP TAPE_PULSE_COMMON
TAPE_PULSE_ZERO_END_CHECKSUM:
EXX
LD BC,29
JP TAPE_PULSE_COMMON
TAPE_PULSE_ONE_FIRST:
EXX
LD BC,61
JP TAPE_PULSE_COMMON
TAPE_PULSE_ONE_FIRST_LAST:
EXX
LD BC,59
JP TAPE_PULSE_COMMON
TAPE_PULSE_ONE_SECOND:
EXX
LD BC,59
JP TAPE_PULSE_COMMON
TAPE_PULSE_ONE_BOUNDARY:
EXX
LD BC,54
JP TAPE_PULSE_COMMON
TAPE_PULSE_ONE_END_DATA:
EXX
LD BC,56
JP TAPE_PULSE_COMMON
TAPE_PULSE_ONE_END_CHECKSUM:
EXX
LD BC,62
JP TAPE_PULSE_COMMON
TAPE_PULSE_COMMON:
LD A,(IY-3)
XOR 8
LD (IY-3),A
OUT ($fe),A
TAPE_PULSE_COUNT:
DEC BC
LD A,B
OR C
JR NZ,TAPE_PULSE_COUNT
EXX
RET
