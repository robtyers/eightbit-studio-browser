; In-place editor tokenisation. The IDE's native token stream uses the same bytes.
MAIN_PROMPT EQU $2000
LEX_ENTRY:
CP 1
JP Z,LEX_PRINT_TOKEN
CP 2
JP Z,LEX_BUFFER
CP 3
JP Z,LEX_EXPAND_LINE
CP 4
JP Z,LEX_EXPAND_KEYWORD
CP 5
JP Z,LEX_TOKEN_WIDTH
LD HL,(E_LINE)
LD DE,(E_LINE)
LD B,0
LEX_CHARACTER:
LD A,(HL)
CP 13
JP Z,LEX_FINISH
CP 34
JP Z,LEX_QUOTE
LD A,B
CP 1
JP Z,LEX_COPY
LD A,(HL)
CP 14
JP Z,LEX_NUMBER_BYTES
CP 234
JP Z,LEX_NATIVE_COMMENT
CALL TOKEN_BYTE
JP NC,LEX_NATIVE_TOKEN
LD A,B
CP 2
JP Z,LEX_IDENTIFIER
OR A
JP NZ,LEX_COPY
LEX_LOOKUP:
PUSH DE
PUSH HL
LD IX,LEX_WORDS
LEX_TRY:
LD A,(IX+0)
OR A
JP Z,LEX_UNMATCHED
LD C,A
LD B,0
PUSH IX
POP DE
INC DE
INC DE
PUSH HL
LEX_MATCH:
LD A,(HL)
CP 'a'
JP C,LEX_MATCH_CASE
CP 'z'+1
JP NC,LEX_MATCH_CASE
AND $df
LEX_MATCH_CASE:
PUSH BC
LD C,A
LD A,(DE)
CP C
POP BC
JP NZ,LEX_NEXT
INC HL
INC DE
DEC C
JP NZ,LEX_MATCH
LD A,(IX+1)
CP 199
JP C,LEX_WORD_BOUNDARY
CP 202
JP C,LEX_MATCHED
LEX_WORD_BOUNDARY:
; The # punctuation terminates OPEN/CLOSE even before a numeric stream.
LD A,(IX+1)
CP 211
JP Z,LEX_MATCHED
CP 212
JP Z,LEX_MATCHED
LD A,(HL)
OR $20
CP 'a'
JP C,LEX_MATCH_DIGIT
CP 'z'+1
JP C,LEX_NEXT
LEX_MATCH_DIGIT:
CP '0'
JP C,LEX_MATCH_DOLLAR
CP '9'+1
JP C,LEX_NEXT
LEX_MATCH_DOLLAR:
CP '$'
JP Z,LEX_NEXT
LEX_MATCHED:
LD A,(IX+1)
CALL TOKEN_BYTE
JR NC,LEX_MODEL_MATCH
CALL MODEL_128
JP Z,LEX_NEXT
LEX_MODEL_MATCH:
LD A,(IX+1)
POP BC
POP BC
POP DE
LD (DE),A
INC DE
CP 234
JP Z,LEX_COMMENT
LD B,0
JP LEX_CHARACTER
LEX_NEXT:
POP HL
LD C,(IX+0)
LD B,0
INC BC
INC BC
ADD IX,BC
JP LEX_TRY
LEX_UNMATCHED:
POP HL
POP DE
LD B,0
LD A,(HL)
OR $20
CP 'a'
JP C,LEX_COPY
CP 'z'+1
JP NC,LEX_COPY
LD B,2
LEX_COPY:
LD A,(HL)
LD (DE),A
INC HL
INC DE
JP LEX_CHARACTER
LEX_IDENTIFIER:
LD A,(HL)
OR $20
CP 'a'
JP C,LEX_IDENTIFIER_DIGIT
CP 'z'+1
JP C,LEX_COPY
LEX_IDENTIFIER_DIGIT:
CP '0'
JP C,LEX_IDENTIFIER_END
CP '9'+1
JP C,LEX_COPY
LEX_IDENTIFIER_END:
CP '$'
JP Z,LEX_COPY
LD B,0
JP LEX_LOOKUP
LEX_QUOTE:
LD A,B
XOR 1
LD B,A
JP LEX_COPY
LEX_COMMENT:
LD A,(HL)
CP 13
JP Z,LEX_FINISH
LD (DE),A
INC HL
INC DE
JP LEX_COMMENT
LEX_NATIVE_TOKEN:
LD B,0
JP LEX_COPY
LEX_NATIVE_COMMENT:
LD (DE),A
INC HL
INC DE
JP LEX_COMMENT
LEX_NUMBER_BYTES:
PUSH BC
LD BC,6
LDIR
POP BC
JP LEX_CHARACTER
LEX_FINISH:
LD (DE),A
INC DE
LD ($5c61),DE
LD (STKBOT),DE
LD (STKEND),DE
LD HL,(E_LINE)
LD (CH_ADD),HL
RET
LEX_BUFFER:
; Reuse the exact lexer for INPUT while retaining its allocated workspace and
; the original programme command line. LINE input deliberately bypasses this.
PUSH HL
LD DE,(E_LINE)
PUSH DE
LD DE,($5c61)
PUSH DE
LD DE,(STKBOT)
PUSH DE
LD DE,(STKEND)
PUSH DE
LD (E_LINE),HL
XOR A
CALL LEX_ENTRY
POP DE
LD (STKEND),DE
POP DE
LD (STKBOT),DE
POP DE
LD ($5c61),DE
POP DE
LD (E_LINE),DE
POP HL
LD (CH_ADD),HL
RET
LEX_PRINT_TOKEN:
LD IX,LEX_WORDS
LEX_PRINT_FIND:
LD A,(IX+0)
OR A
RET Z
LD A,(IX+1)
CP C
JR Z,LEX_PRINT_WORD
LD E,(IX+0)
LD D,0
INC DE
INC DE
ADD IX,DE
JR LEX_PRINT_FIND
LEX_PRINT_WORD:
LD B,(IX+0)
PUSH IX
POP HL
INC HL
INC HL
LEX_PRINT_LETTER:
LD A,(HL)
RST $10
INC HL
DJNZ LEX_PRINT_LETTER
LD A,C
CP 199
JR C,LEX_PRINT_SPACE
CP 202
RET C
LEX_PRINT_SPACE:
LD A,32
RST $10
RET
; Expand a stored line for editing, omitting hidden numeric cells only outside
; strings/comments. KCUR names the destination; BC bounds the output including CR.
LEX_EXPAND_LINE:
PUSH IX
LD IX,0
ADD IX,SP
PUSH HL
LD DE,($5c5b)
PUSH DE
PUSH BC
PUSH AF
LD (IX-7),0
LEX_EXPAND_NEXT:
LD L,(IX-2)
LD H,(IX-1)
LD DE,($5c4b)
PUSH HL
OR A
SBC HL,DE
POP HL
JP NC,LEX_EXPAND_INVALID
LD A,(HL)
INC HL
LD (IX-2),L
LD (IX-1),H
CP 13
JP Z,LEX_EXPAND_END
CP 34
JR NZ,LEX_EXPAND_MODE
LD C,A
LD A,(IX-7)
CP 2
JR Z,LEX_EXPAND_QUOTE_COPY
XOR 1
LD (IX-7),A
LEX_EXPAND_QUOTE_COPY:
LD A,C
JR LEX_EXPAND_COPY
LEX_EXPAND_MODE:
LD C,A
LD A,(IX-7)
OR A
LD A,C
JR NZ,LEX_EXPAND_COPY
CP 14
JR NZ,LEX_EXPAND_TOKEN
LD DE,5
ADD HL,DE
LD (IX-2),L
LD (IX-1),H
JP LEX_EXPAND_NEXT
LEX_EXPAND_TOKEN:
CP 234
JR NZ,LEX_EXPAND_COPY
LD (IX-7),2
JR LEX_EXPAND_COPY
LEX_EXPAND_COPY:
CALL LEX_EXPAND_PUT
JP LEX_EXPAND_NEXT
LEX_EXPAND_END:
CALL LEX_EXPAND_PUT
LD L,(IX-4)
LD H,(IX-3)
DEC HL
LD SP,IX
POP IX
RET
LEX_EXPAND_PUT:
PUSH HL
PUSH BC
PUSH AF
LD L,(IX-6)
LD H,(IX-5)
LD A,H
OR L
JP Z,LEX_EXPAND_INVALID
DEC HL
LD (IX-6),L
LD (IX-5),H
LD L,(IX-4)
LD H,(IX-3)
POP AF
LD (HL),A
INC HL
LD (IX-4),L
LD (IX-3),H
POP BC
POP HL
RET
LEX_EXPAND_INVALID:
LD A,15
LD (ERR_NR),A
JP REPORT_ERROR
; Copy one original keyword into the editor's bounded 16-byte temporary area.
LEX_EXPAND_KEYWORD:
LD HL,LEX_WORDS
LEX_KEYWORD_FIND:
LD A,(HL)
OR A
JP Z,LEX_EXPAND_INVALID
LD B,A
INC HL
LD A,(HL)
INC HL
CP C
JR Z,LEX_KEYWORD_COPY
LD E,B
LD D,0
ADD HL,DE
JR LEX_KEYWORD_FIND
LEX_KEYWORD_COPY:
LD DE,($5c5b)
LD A,B
CP 14
JP NC,LEX_EXPAND_INVALID
LEX_KEYWORD_CHARACTER:
LD A,(HL)
LD (DE),A
INC HL
INC DE
DJNZ LEX_KEYWORD_CHARACTER
LD A,C
CP 199
JR C,LEX_KEYWORD_SPACE
CP 202
JR C,LEX_KEYWORD_END
LEX_KEYWORD_SPACE:
LD A,32
LD (DE),A
INC DE
LEX_KEYWORD_END:
LD A,13
LD (DE),A
EX DE,HL
RET
LEX_TOKEN_WIDTH:
LD HL,LEX_WORDS
LEX_WIDTH_FIND:
LD A,(HL)
OR A
JP Z,LEX_EXPAND_INVALID
LD B,A
INC HL
LD A,(HL)
INC HL
CP C
JR Z,LEX_WIDTH_FOUND
LD E,B
LD D,0
ADD HL,DE
JR LEX_WIDTH_FIND
LEX_WIDTH_FOUND:
LD L,B
LD H,0
LD A,C
CP 199
JR C,LEX_WIDTH_SPACE
CP 202
RET C
LEX_WIDTH_SPACE:
INC HL
RET
LEX_WORDS:
