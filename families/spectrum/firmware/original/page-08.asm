; Published temporary/permanent colour state and attribute application.
MAIN_PROMPT EQU $2000
COLOUR_ENTRY:
CP 32
JP Z,COLOUR_APPLY
CP 64
JP Z,COLOUR_RESET
CP 65
JP Z,COLOUR_PERMANENT
CP 16
JP C,COLOUR_INVALID
CP 22
JP NC,COLOUR_INVALID
CP 20
JP NC,COLOUR_BINARY
CP 18
JP NC,COLOUR_INTENSITY
LD B,7
LD D,16
CP 16
JR Z,COLOUR_INK
LD B,$38
LD D,64
COLOUR_INK:
LD A,C
CP 10
JP NC,COLOUR_INVALID
LD A,D
CPL
LD E,A
LD A,(P_FLAG)
AND E
LD (P_FLAG),A
LD A,C
CP 8
JR Z,COLOUR_TRANSPARENT
CP 9
JR NZ,COLOUR_REGULAR
LD A,(P_FLAG)
OR D
LD (P_FLAG),A
LD C,0
COLOUR_REGULAR:
LD A,D
CP 64
LD A,C
JR NZ,COLOUR_VALUE_READY
RLCA
RLCA
RLCA
COLOUR_VALUE_READY:
LD C,A
JR COLOUR_STORE
COLOUR_INTENSITY:
LD B,$80
CP 18
JR Z,COLOUR_FLASH
LD B,$40
COLOUR_FLASH:
LD A,C
CP 8
JR Z,COLOUR_TRANSPARENT
CP 2
JP NC,COLOUR_INVALID
OR A
JR Z,COLOUR_VALUE_READY
LD A,B
JR COLOUR_VALUE_READY
COLOUR_TRANSPARENT:
LD A,($5c90)
OR B
LD ($5c90),A
RET
COLOUR_STORE:
LD A,B
CPL
LD E,A
LD A,($5c90)
AND E
LD ($5c90),A
LD A,(ATTR_T)
AND E
OR C
LD (ATTR_T),A
RET
COLOUR_BINARY:
LD D,1
CP 21
JR Z,COLOUR_BINARY_VALUE
LD D,4
COLOUR_BINARY_VALUE:
LD A,C
CP 2
JP NC,COLOUR_INVALID
OR A
JR Z,COLOUR_BINARY_CLEAR
LD A,(P_FLAG)
OR D
LD (P_FLAG),A
RET
COLOUR_BINARY_CLEAR:
LD A,D
CPL
LD D,A
LD A,(P_FLAG)
AND D
LD (P_FLAG),A
RET
COLOUR_RESET:
LD A,(ATTR_P)
LD (ATTR_T),A
LD A,($5c8e)
LD (MASK_T),A
LD A,(P_FLAG)
AND $aa
LD B,A
RRCA
OR B
LD (P_FLAG),A
RET
COLOUR_PERMANENT:
LD A,(ATTR_T)
LD (ATTR_P),A
LD A,(MASK_T)
LD ($5c8e),A
LD A,(P_FLAG)
AND $55
LD B,A
RLCA
OR B
LD (P_FLAG),A
RET
COLOUR_APPLY:
LD A,(MASK_T)
LD B,A
LD A,(HL)
AND B
LD C,A
LD A,B
CPL
LD B,A
LD A,(ATTR_T)
AND B
OR C
LD C,A
LD A,(P_FLAG)
BIT 4,A
JR Z,COLOUR_CONTRAST_PAPER
LD A,C
AND $38
CP $20
LD A,C
JR NC,COLOUR_CONTRAST_DARK_INK
OR 7
JR COLOUR_CONTRAST_INK_DONE
COLOUR_CONTRAST_DARK_INK:
AND $f8
COLOUR_CONTRAST_INK_DONE:
LD C,A
COLOUR_CONTRAST_PAPER:
LD A,(P_FLAG)
BIT 6,A
JR Z,COLOUR_APPLY_DONE
LD A,C
AND 7
CP 4
LD A,C
JR NC,COLOUR_CONTRAST_DARK_PAPER
OR $38
JR COLOUR_APPLY_WRITE
COLOUR_CONTRAST_DARK_PAPER:
AND $c7
JR COLOUR_APPLY_WRITE
COLOUR_APPLY_DONE:
LD A,C
COLOUR_APPLY_WRITE:
LD (HL),A
RET
COLOUR_INVALID:
LD A,19
LD (ERR_NR),A
JP REPORT_ERROR
